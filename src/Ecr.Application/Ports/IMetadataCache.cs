using Ecr.Domain.Entities.Configuration;

namespace Ecr.Application.Ports;

/// <summary>
/// Кеш метаданих шаблону. Опублікована версія структурно незмінна, тому ключ
/// <c>v{id}:r{rev}</c> робить інвалідацію непотрібною: презентаційна правка
/// створює новий ключ, а не псує старий (D-16). Це прибирає когерентність кешу
/// між інстансами як клас проблеми.
/// </summary>
public interface IMetadataCache
{
    /// <summary>Повна структура версії шаблону.</summary>
    public Task<TemplateVersionSnapshot> GetAsync(int templateVersionId, CancellationToken ct);

    /// <summary>
    /// Скидає запис. Потрібно після <c>Publish</c>, міграції — і після
    /// кожної структурної правки чернетки (<c>PUT/DELETE …/sheets/{code}</c>
    /// та наступні зрізи авторства структури).
    /// </summary>
    /// <remarks>
    /// ⚠ До появи авторства структури через API це справді було потрібно
    /// «лише після Publish»: єдиним, хто міняв <c>SheetDef</c> і сусідів поза
    /// тестами, був офлайновий <c>Ecr.DataGen</c>, який працює до першого
    /// прогріву кешу. Структурний <c>PUT</c> у працюючому інстансі зламав би
    /// це припущення мовчки: додавання аркуша не піднімає
    /// <c>PresentationRevision</c> (не презентаційна правка), тож без явного
    /// скидання прогрітий кеш віддавав би знімок ДО правки, доки версію не
    /// опублікують.
    /// </remarks>
    public Task InvalidateAsync(int templateVersionId, CancellationToken ct);

    /// <summary>
    /// Похідні від версії дані (граф залежностей формул тощо), що живуть РІВНО стільки, скільки знімок версії:
    /// тим самим ключем ревізії, тим самим токеном інвалідації (<see cref="InvalidateAsync"/>) і тією ж стелею життя
    /// (заморожена версія — довго, чернетка — вікно ревізії).
    /// </summary>
    /// <typeparam name="T">Тип значення; ЗНАЧЕННЯ СПІЛЬНЕ між запитами — незмінне за побудовою.</typeparam>
    /// <param name="templateVersionId">Версія шаблону.</param>
    /// <param name="kind">Вид даних — частина ключа; один вид = один тип й одне джерело.</param>
    /// <param name="load">Читання з бази; виконується щонайбільше один раз на політ і ключ.</param>
    /// <param name="ct">Токен скасування.</param>
    /// <param name="shortLived">Значення, що живе не довше за вікно ревізії; <c>null</c> — звичайна стеля.</param>
    /// <returns>Значення з кешу або щойно прочитане.</returns>
    /// <remarks>
    /// ⛔ Чому не окремий кеш: окремий мусив би сам знати, коли версія змінилася (публікація, міграція, правка
    /// чернетки) — і розійшовся б зі знімком на першій же новій точці інвалідації. Тут кожен виклик
    /// <see cref="InvalidateAsync"/> (а їх ставлять усі структурні обробники) скидає й похідні.
    /// <para>
    /// ✎ Аудит 31.10 (F3): <paramref name="shortLived"/> — значення, яке не можна тримати довше за вікно ревізії навіть
    /// на замороженій версії (відповідь «ще немає» про стан, що змінюється БЕЗ підйому ревізії, напр. «позначок ручних
    /// значень немає»): для нього стеля життя — як у чернетки, а не години.
    /// </para>
    /// </remarks>
    public Task<T> GetDerivedAsync<T>(
        int templateVersionId, string kind, Func<CancellationToken, Task<T>> load, CancellationToken ct,
        Func<T, bool>? shortLived = null)
        where T : class;
}
