namespace Ecr.Application.Ports;

/// <summary>
/// Q-17: сховище комірок, що вміє кешувати значення екземплярів-власників на ОДНУ задачу перерахунку.
/// </summary>
/// <remarks>
/// <para>
/// Перерахунок читає кілька періодів поспіль (поточний і зсуви <c>[Period:-N]</c>/<c>[Period:#k]</c>), і кожне читання
/// зрізу екземпляра перегляду підтягує введені комірки власників (≤ 13 партицій). Без сесії власники читалися б
/// заново для кожного періоду.
/// </para>
/// <para>
/// ⛔ Час життя кешу = час життя сесії (одна задача); інвалідація не потрібна, бо перерахунок НЕ пише введені комірки
/// власників — лише обчислені комірки екземпляра перегляду. Поза сесією кешу немає і сховище поводиться як завжди.
/// </para>
/// </remarks>
public interface IOwnerReadSession
{
    /// <summary>Починає сесію; кеш скидається, коли закрито останню з вкладених сесій.</summary>
    /// <returns>Токен завершення сесії.</returns>
    public IDisposable BeginOwnerReadSession();
}
