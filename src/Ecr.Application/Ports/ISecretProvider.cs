namespace Ecr.Application.Ports;

/// <summary>
/// Значення секрету за його <b>іменем</b>.
/// </summary>
/// <remarks>
/// ⛔ У базі й конфігурації живе лише ім'я секрету (<c>ext.DataSource.SecretName</c>,
/// ФВ-6.11, D-11). Значення приходить із середовища і **ніколи** не потрапляє
/// ні в <c>appsettings.json</c>, ні в резервну копію, ні в лог: пароль,
/// записаний «тимчасово, щоб запрацювало», лишається назавжди і виїздить
/// разом із першим же дампом.
/// <para>
/// Метод синхронний навмисно: читання зі змінних середовища не має вводити
/// в код await, який виглядатиме як звернення до сховища секретів. Коли
/// з'явиться справжній Key Vault, порт стане асинхронним — і це буде видно
/// в кожному виклику.
/// </para>
/// </remarks>
public interface ISecretProvider
{
    /// <summary>Значення секрету; <c>null</c> — не налаштовано.</summary>
    /// <param name="secretName">Ім'я секрету з конфігурації джерела.</param>
    /// <remarks>
    /// ⚠ Відсутній секрет — це <c>null</c>, а не виняток: частина джерел
    /// ходить під інтегрованою автентифікацією службового облікового запису
    /// (D-34), і секрет їм не потрібен взагалі.
    /// </remarks>
    public string? Find(string secretName);
}
