namespace Ecr.Application.Common;

/// <summary>
/// Поточний користувач запиту. Реалізація в <c>Ecr.Api</c> дістає його з
/// cookie — і саме тому нижче рівня входу **не видно**, як він увійшов
/// (ФВ-6.2).
/// </summary>
public interface ICurrentUser
{
    /// <summary>Ідентифікатор; <c>null</c> для анонімного запиту.</summary>
    public int? UserId { get; }

    /// <summary>Ім'я для аудиту і повідомлень.</summary>
    public string? UserName { get; }

    /// <summary>Наскрізний ідентифікатор запиту.</summary>
    public string CorrelationId { get; }

    /// <summary>Мова інтерфейсу для локалізації повідомлень.</summary>
    public string Language { get; }

    /// <summary>
    /// SID груп безпеки з токена входу; порожньо для локального користувача.
    /// </summary>
    /// <remarks>
    /// ⚠ Членство береться <b>з токена</b>, а не запитом до каталогу
    /// (ФВ-6.15a): каталог відповідає повільно, іноді не відповідає взагалі, і
    /// доступ, який залежить від його доступності, перестає бути доступом.
    /// <para>
    /// ⛔ Саме на групу за ФВ-6.15 призначається більшість ролей доменних
    /// користувачів. Доки цей перелік не доходив до профілю (`P-02`), у
    /// продуктиві вони отримали б лише те, що призначено особисто — тобто
    /// майже нічого.
    /// </para>
    /// </remarks>
    public IReadOnlyList<string> GroupSids { get; }
}
