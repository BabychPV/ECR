namespace Ecr.Domain.ValueObjects;

/// <summary>
/// Вікно чинності — **напівінтервал** <c>[FromInclusive, ToExclusive)</c>
/// (директива ПК-1 №05 §7, пастка 5).
/// </summary>
/// <remarks>
/// ⛔ Це ЄДИНЕ формулювання правила меж чинності для довідників і констант.
/// Копії цієї умови жили в трьох місцях — <c>RegistryEntry.IsValidOn</c>,
/// <c>ConstantResolver.ResolveAsync</c> і <c>PeriodAccessRules.SourceWindow</c>, —
/// і всі три були **закритим** інтервалом (<c>date &lt;= ValidTo</c>). Дослівний
/// збіг трьох формулювань не рятує: він тримається рівно до першої правки
/// одного з них.
///
/// ⛔ **Чому напівінтервал, а не «включно з обох боків».** У джерелі
/// (чинна система ECR) верхня межа записана як <c>datetime</c> трьома різними
/// способами: <c>9999-02-20</c> і <c>9999-12-31</c> — сентинел «без обмеження»;
/// <c>2024-12-31 23:59:59</c> — «до кінця року»; і 24 рядки з
/// <c>2024-12-31 12:59:59</c>, де кінець доби набрали з помилкою. Закритий
/// інтервал змушує зберігати «останню чинну мить», і саме тому в джерелі
/// з'явилися <c>23:59:59</c> — а слідом за ними <c>12:59:59</c>, яке відрізає
/// одинадцять годин доби і виглядає точнісінько так само.
/// Напівінтервал зберігає межу як **першу нечинну дату**, і в наших даних
/// не існує ані <c>23:59:59</c>, ані сентинелів: «без обмеження» — це
/// <c>null</c>.
///
/// ⚠ Правило меж дії **призначення ролі** (<c>RoleAssignment.IsEffectiveOn</c>)
/// свідомо інше — воно закрите з обох боків, — і це не недогляд:
/// див. <c>D2-123</c>. Там межа походить не з міграції, а з наказу
/// («підміна до 31 травня»), і напівінтервал відібрав би права на день
/// раніше, ніж написано в наказі.
/// </remarks>
/// <param name="FromInclusive">
/// Перший чинний день; <c>null</c> — «чинне від початку».
/// </param>
/// <param name="ToExclusive">
/// **Перший НЕчинний день**, а не останній чинний; <c>null</c> — «без
/// обмеження». Вікно календарного 2024 року — це
/// <c>[2024-01-01, 2025-01-01)</c>.
/// </param>
public readonly record struct ValidityWindow(DateOnly? FromInclusive, DateOnly? ToExclusive)
{
    /// <summary>Вікно без жодної межі: чинне завжди.</summary>
    public static ValidityWindow Always => default;

    /// <summary>
    /// Вікно порожнє — не чинне НІКОЛИ.
    /// </summary>
    /// <remarks>
    /// ⚠ <c>ToExclusive == FromInclusive</c> теж порожнє, і це відмінність
    /// напівінтервала від закритого: там рівність меж означала рівно один
    /// чинний день, тут — жодного. Саме тому перевірка вводу в
    /// <c>SetValidity</c> посилилася з <c>&lt;</c> на <c>&lt;=</c>.
    /// </remarks>
    public bool IsEmpty
        => FromInclusive is { } from && ToExclusive is { } to && to <= from;

    /// <summary>
    /// Останній чинний день — **лише для показу людині**.
    /// </summary>
    /// <remarks>
    /// ⛔ Порівнювати через нього НЕ можна: це друге подання тієї самої межі,
    /// а два подання розходяться. Воно існує тому, що людина читає «дозвіл
    /// чинний до 31 грудня», а не «до 1 січня не включно», і повідомлення про
    /// відмову має говорити її мовою.
    /// <c>null</c> — межі немає (або вікно порожнє й останнього дня не існує).
    /// </remarks>
    public DateOnly? LastValidDay
        => ToExclusive is { } to && !IsEmpty ? to.AddDays(-1) : null;

    /// <summary>Чи чинне вікно на вказану дату.</summary>
    /// <param name="date">Дата в календарі майданчика.</param>
    /// <returns><c>true</c> — дата всередині напівінтервала.</returns>
    public bool Contains(DateOnly date)
        => (FromInclusive is null || date >= FromInclusive)
        && (ToExclusive is null || date < ToExclusive);

    /// <summary>
    /// Чи перетинається вікно з відрізком календаря (місяцем, кварталом).
    /// </summary>
    /// <param name="startInclusive">Перший день відрізка.</param>
    /// <param name="endExclusive">Перший день ПІСЛЯ відрізка.</param>
    /// <returns><c>true</c> — є бодай один спільний день.</returns>
    /// <remarks>
    /// ⚠ Місяць порівнюється як ВІДРІЗОК, а не як дата (<c>ФВ-2.15</c>,
    /// правило <c>SourceWindow</c>): дозвіл, чинний до 15 червня, червень
    /// усе-таки покриває — викид за першу половину місяця стався в межах
    /// дозволу, і заборонити ввід означало б втратити реальні дані.
    ///
    /// ⛔ Обидва відрізки напівінтервальні, тому перетин — це строге
    /// <c>&lt;</c> з обох боків. Зі змішаними поданнями (місяць закритий,
    /// вікно відкрите) помилка на день з'являється рівно на межі місяця й
    /// не помічається на жодних інших даних.
    /// </remarks>
    public bool OverlapsSegment(DateOnly startInclusive, DateOnly endExclusive)
        => (ToExclusive is null || startInclusive < ToExclusive)
        && (FromInclusive is null || FromInclusive < endExclusive);
}
