namespace Ecr.Expressions.Evaluation;

/// <summary>
/// Бюджет ОДНОГО обчислення виразу, лічений у КРОКАХ, а не в секундах.
/// </summary>
/// <remarks>
/// ⛔ **Чому кроки, а не годинник.** Спокусливо поставити сюди
/// <see cref="System.Threading.CancellationToken"/> із таймаутом — так зроблено
/// поверхом вище, в <c>CalculationOrchestrator</c>. Але там токен розриває
/// роботу МІЖ виразами, і його недетермінованість нічого не вирішує; тут вона
/// вирішувала б усе. Той самий вираз над тими самими даними мусить дати той
/// самий результат на машині розробника, на агенті CI під навантаженням і в
/// нічному перерахунку — інакше звірка з еталоном (<c>ФВ-9.5</c>) і приймальні
/// тести методології (<c>calc.TestCase</c>, <c>ФВ-9.12</c>, <c>ФВ-13.7</c>)
/// стають випадковими: методологія, зелена вдень, червоніє вночі, і публікацію
/// блокує не помилка автора, а сусідній процес на агенті. Лічильник кроків
/// такого не вміє: він рахує РОБОТУ, а не час, і на тих самих входах завжди
/// дає те саме число.
///
/// ⚠ Пам'ять обмежується ТИМ САМИМ лічильником, а не окремим. Заміряно
/// (<c>ExpressionEvaluationBudgetTests</c>): 5.4 ГБ алокацій одного прогону —
/// це не великі об'єкти, а мільйони дрібних, по одному на прочитане значення.
/// Отже число прочитаних значень і є мірою пам'яті; другий лічильник із
/// власним числом означав би дві різні правди про те, який вираз завеликий
/// (та сама помилка, яку вже прибирали з <c>PredicateValidator</c>).
///
/// ⚠ Екземпляр — НА ОДИН виклик <c>Evaluator.Evaluate</c>, не на
/// обчислювач: обчислювач один на застосунок і працює з багатьох потоків
/// одразу.
/// </remarks>
/// <param name="maxSteps">Скільки кроків дозволено.</param>
public sealed class EvaluationBudget(int maxSteps)
{
    private int _spent;

    /// <summary>Скільки кроків дозволено цьому обчисленню.</summary>
    public int MaxSteps { get; } = maxSteps > 0
        ? maxSteps
        : throw new ArgumentOutOfRangeException(nameof(maxSteps));

    /// <summary>Скільки кроків уже витрачено.</summary>
    /// <remarks>
    /// ⚠ Публічне саме заради ЗАМІРУ: тест, який доводить, що чинні форми
    /// вкладаються в бюджет, мусить назвати число, а не сказати «не впало».
    /// </remarks>
    public int Spent => _spent;

    /// <summary>Чи бюджет уже вичерпано.</summary>
    public bool IsExhausted => _spent >= MaxSteps;

    /// <summary>
    /// Списує роботу; <c>false</c> — бюджет вичерпано, далі рахувати не можна.
    /// </summary>
    /// <param name="steps">Скільки кроків коштувала робота; мінімум один.</param>
    /// <remarks>
    /// ⚠ Лічильник НЕ відкочується і не скидається: вичерпаний бюджет лишається
    /// вичерпаним до кінця обчислення. Інакше вираз із десятьма гілками, кожна
    /// з яких «майже вклалася», проходив би цілком.
    /// </remarks>
    public bool TryConsume(int steps = 1)
    {
        if (_spent >= MaxSteps)
        {
            return false;
        }

        // ⚠ Насичення, а не переповнення: група на два мільярди значень —
        // не привід отримати від'ємний лічильник і нескінченний бюджет.
        _spent = steps >= MaxSteps - _spent ? MaxSteps : _spent + Math.Max(1, steps);

        return _spent < MaxSteps;
    }
}

/// <summary>
/// Контекст, здатний ПОЗИЧИТИ бюджет зовнішнього обчислення вкладеному.
/// </summary>
/// <remarks>
/// ⛔ Існує рівно через один випадок, і без нього бюджет був би декорацією.
/// <c>SliceEvaluationContext.Read</c> для предикатного посилання
/// (<c>[Items].[WHERE …].[Amount]</c>) обчислює умову НАД КОЖНИМ рядком
/// таблиці — власним викликом <c>Evaluator.Evaluate</c>. Якби той виклик
/// заводив собі свіжий бюджет, зовнішній не побачив би ЖОДНОГО з цих рядків:
/// предикат, який не відібрав нічого, повертає порожню групу, тобто нуль
/// значень, — а сканування 471 рядка вже сталося. Саме на цьому шляху й
/// заміряно 16.8 с і 5.4 ГБ.
///
/// ⚠ Реалізація — звичайна авто-властивість. Контекст і без того має змінюваний
/// стан на виклик (<c>CurrentRowKey</c>), тобто вже не спільний між потоками;
/// бюджет нічого до цього не додає.
/// </remarks>
public interface IBudgetedEvaluationContext : IEvaluationContext
{
    /// <summary>
    /// Бюджет поточного обчислення; <c>null</c> — обчислення не триває.
    /// Ставить і знімає <c>Evaluator.Evaluate</c>.
    /// </summary>
    public EvaluationBudget? Budget { get; set; }
}
