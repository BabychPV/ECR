namespace Ecr.Expressions.Evaluation;

/// <summary>
/// Бюджет ОДНОГО обчислення виразу, лічений у КРОКАХ, а не в секундах.
/// </summary>
/// <remarks>
/// ⛔ **Чому кроки, а не годинник.** Спокусливо поставити сюди
/// <see cref="System.Threading.CancellationToken"/> із таймаутом — так зроблено
/// поверхом вище, в <c>CalculationOrchestrator</c>. Але там токен розриває
/// роботу МІЖ виразами, і його недетермінованість нічого не вирішує; тут вона
/// вирішувала б усе. Той самий вираз над тими самими даними мусить дати той
/// самий результат на машині розробника, на агенті CI під навантаженням і в
/// нічному перерахунку — інакше звірка з еталоном (<c>ФВ-9.5</c>) і приймальні
/// тести методології (<c>calc.TestCase</c>, <c>ФВ-9.12</c>, <c>ФВ-13.7</c>)
/// стають випадковими: методологія, зелена вдень, червоніє вночі, і публікацію
/// блокує не помилка автора, а сусідній процес на агенті. Лічильник кроків
/// такого не вміє: він рахує РОБОТУ, а не час, і на тих самих входах завжди
/// дає те саме число.
///
/// ⚠ Пам'ять обмежується ТИМ САМИМ лічильником, а не окремим. Заміряно
/// (<c>ExpressionEvaluationBudgetTests</c>): 5.4 ГБ алокацій одного прогону —
/// це не великі об'єкти, а мільйони дрібних, по одному на прочитане значення.
/// Отже число прочитаних значень і є мірою пам'яті; другий лічильник із
/// власним числом означав би дві різні правди про те, який вираз завеликий
/// (та сама помилка, яку вже прибирали з <c>PredicateValidator</c>).
///
/// ⚠ Екземпляр — НА ОДИН виклик <c>Evaluator.Evaluate</c>, не на
/// обчислювач: обчислювач один на застосунок і працює з багатьох потоків
/// одразу.
/// </remarks>
/// <param name="maxSteps">Скільки кроків дозволено.</param>
public sealed class EvaluationBudget(int maxSteps)
{
    /// <summary>
    /// Скільки вкладених спусків обчислювача дозволено — межа СТЕКА.
    /// </summary>
    /// <remarks>
    /// ⛔ **Другий лічильник тут неминучий, і це не суперечить абзацу вище про
    /// пам'ять.** Кроки міряють РОБОТУ, і саме тому вони сліпі до глибини:
    /// плаский ланцюг <c>1+1+…+1</c> з тисячі доданків коштує ~2000 кроків із
    /// дозволених 20 000 — тобто межу кроків він не чіпає взагалі, — а дерево
    /// дає ліву гілку глибиною 1000, і обчислення вмирає в стеку задовго до
    /// того, як лічильник кроків щось помітить. Це різні ресурси, і один
    /// лічильник на два не відповів би, який саме вичерпано.
    ///
    /// ⛔ **Замір, а не обережність** (окремий процес, <c>evalprobe</c>, той
    /// самий прийом, яким міряли парсер). Один спуск коштує ~1.34 КБ стека в
    /// <c>Release</c> і ~1.48 КБ у <c>Debug</c>: на потоці зі стандартним
    /// стеком 1 МБ <c>1+1+…+1</c> із 1000 доданків (рівно 1999 символів —
    /// стеля <c>nvarchar(2000)</c> колонки <c>cfg.FormulaDef.Expression</c>)
    /// завершує процес кодом <c>0xC00000FD</c> після 767 повторів циклу
    /// <c>Binary → EvaluateScalar</c>. <c>StackOverflowException</c> у .NET не
    /// перехоплюється: падав би не перерахунок однієї комірки, а весь хост
    /// перерахунку.
    ///
    /// ⚠ **Число затиснуте з двох боків, обидві межі виміряні:**
    /// <list type="bullet">
    /// <item>знизу — парсер уже приймає 63 рівні вкладеності
    /// (<see cref="Parsing.Parser.MaxRecursionDepth"/> = 192 спуски по 3 на
    /// рівень), і кожен такий рівень коштує один спуск ТУТ. Межа ≤ 64
    /// відхиляла б вирази, які парсер щойно прийняв, тобто ламала б
    /// опубліковане. 96 — це півтора рази від стелі парсера;</item>
    /// <item>знизу ж — найглибша формула обох фікстур корпусу коштує <b>5</b>
    /// спусків, тобто запас 19-кратний. Число не оголошене, а ВИМІРЯНЕ цим
    /// самим лічильником (<see cref="Deepest"/>): перелік формул, переписаний
    /// у тест, старіє мовчки;</item>
    /// <item>згори — 96 × 1.48 КБ ≈ 142 КБ: безпечно навіть на потоці зі
    /// стеком 256 КБ (це тест, а не припущення —
    /// <c>EvaluatorDepthGuardTests</c>) і близько семикратного запасу до
    /// стандартного 1 МБ.</item>
    /// </list>
    ///
    /// ⚠ **Константа, а не параметр конструктора** — на відміну від
    /// <see cref="MaxSteps"/>. Кроки — це ПОЛІТИКА викликача (скільки роботи
    /// він готовий оплатити), а глибина — фізична властивість машини: стек у
    /// потоку один, і вираз, що його переповнює, переповнює його незалежно від
    /// того, з якою щедрістю викликач роздав кроки.
    /// </remarks>
    public const int MaxNestingDepth = 96;

    private int _spent;
    private int _depth;
    private int _deepest;

    /// <summary>Скільки кроків дозволено цьому обчисленню.</summary>
    public int MaxSteps { get; } = maxSteps > 0
        ? maxSteps
        : throw new ArgumentOutOfRangeException(nameof(maxSteps));

    /// <summary>Скільки кроків уже витрачено.</summary>
    /// <remarks>
    /// ⚠ Публічне саме заради ЗАМІРУ: тест, який доводить, що чинні форми
    /// вкладаються в бюджет, мусить назвати число, а не сказати «не впало».
    /// </remarks>
    public int Spent => _spent;

    /// <summary>Чи бюджет уже вичерпано.</summary>
    public bool IsExhausted => _spent >= MaxSteps;

    /// <summary>
    /// Списує роботу; <c>false</c> — бюджет вичерпано, далі рахувати не можна.
    /// </summary>
    /// <param name="steps">Скільки кроків коштувала робота; мінімум один.</param>
    /// <remarks>
    /// ⚠ Лічильник НЕ відкочується і не скидається: вичерпаний бюджет лишається
    /// вичерпаним до кінця обчислення. Інакше вираз із десятьма гілками, кожна
    /// з яких «майже вклалася», проходив би цілком.
    /// </remarks>
    public bool TryConsume(int steps = 1)
    {
        if (_spent >= MaxSteps)
        {
            return false;
        }

        // ⚠ Насичення, а не переповнення: група на два мільярди значень —
        // не привід отримати від'ємний лічильник і нескінченний бюджет.
        _spent = steps >= MaxSteps - _spent ? MaxSteps : _spent + Math.Max(1, steps);

        return _spent < MaxSteps;
    }

    /// <summary>
    /// Найбільша глибина, якої обчислення досягло.
    /// </summary>
    /// <remarks>
    /// ⚠ Публічне з тієї ж причини, що й <see cref="Spent"/>, і рівно для
    /// одного твердження: «чинні формули корпусу лежать у стільки-то разів
    /// нижче за межу». Без цього числа таке твердження перевірялося б
    /// підбором — обгортанням виразу в дужки, доки він не перестане
    /// обчислюватися, — а підбір міряє межу, а не формулу.
    /// </remarks>
    public int Deepest => _deepest;

    /// <summary>
    /// Заходить на рівень глибше; <c>false</c> — межу вичерпано.
    /// </summary>
    /// <returns>
    /// <c>true</c> — рівень зайнято, викликач ЗОБОВ'ЯЗАНИЙ звільнити його
    /// через <see cref="LeaveNesting"/> (у <c>finally</c>). <c>false</c> —
    /// лічильник НЕ збільшено, і пари <see cref="LeaveNesting"/> не потрібно.
    /// </returns>
    /// <remarks>
    /// ⛔ Асиметрія навмисна. Якби відмова теж збільшувала лічильник, кожен
    /// викликач мусив би пам'ятати про «звільни навіть після відмови» — і саме
    /// такий загублений вихід уже був у чернетці сторожа ПАРСЕРА, де він
    /// перетворював межу глибини на межу РОЗМІРУ: довга, але пласка формула
    /// починала відхилятися як «занадто вкладена».
    ///
    /// ⚠ Лічильник глибини ВІДКОЧУЄТЬСЯ (на відміну від
    /// <see cref="TryConsume"/>), і це не непослідовність: кроки міряють
    /// витрачену роботу, якої вже не повернути, а глибина — зайняті кадри
    /// стека, які вихід із методу справді звільняє. Сусідні підвирази
    /// (двісті аргументів <c>SUM</c>) не накопичують глибину саме тому.
    /// </remarks>
    public bool EnterNesting()
    {
        if (_depth >= MaxNestingDepth)
        {
            return false;
        }

        _depth++;
        if (_depth > _deepest)
        {
            _deepest = _depth;
        }

        return true;
    }

    /// <summary>Звільняє рівень, зайнятий успішним <see cref="EnterNesting"/>.</summary>
    public void LeaveNesting() => _depth--;
}

/// <summary>
/// Контекст, здатний ПОЗИЧИТИ бюджет зовнішнього обчислення вкладеному.
/// </summary>
/// <remarks>
/// ⛔ Існує рівно через один випадок, і без нього бюджет був би декорацією.
/// <c>SliceEvaluationContext.Read</c> для предикатного посилання
/// (<c>[Items].[WHERE …].[Amount]</c>) обчислює умову НАД КОЖНИМ рядком
/// таблиці — власним викликом <c>Evaluator.Evaluate</c>. Якби той виклик
/// заводив собі свіжий бюджет, зовнішній не побачив би ЖОДНОГО з цих рядків:
/// предикат, який не відібрав нічого, повертає порожню групу, тобто нуль
/// значень, — а сканування 471 рядка вже сталося. Саме на цьому шляху й
/// заміряно 16.8 с і 5.4 ГБ.
///
/// ⚠ Реалізація — звичайна авто-властивість. Контекст і без того має змінюваний
/// стан на виклик (<c>CurrentRowKey</c>), тобто вже не спільний між потоками;
/// бюджет нічого до цього не додає.
/// </remarks>
public interface IBudgetedEvaluationContext : IEvaluationContext
{
    /// <summary>
    /// Бюджет поточного обчислення; <c>null</c> — обчислення не триває.
    /// Ставить і знімає <c>Evaluator.Evaluate</c>.
    /// </summary>
    public EvaluationBudget? Budget { get; set; }
}
