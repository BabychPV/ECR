namespace Ecr.Expressions.Evaluation;

/// <summary>
/// Знімок довідників, завантажений ДО обчислення: функції <c>REG*</c> і поля
/// <c>ROW.</c> читають дані лише звідси (FEATURE-REGISTRY-TABLES §5.7).
/// </summary>
/// <remarks>
/// ⛔ Жодного звернення до БД під час обчислення (<c>02b-expressions.md</c>,
/// <c>MethodologyFunctions.cs</c>): рушій синхронний, а прогін — сотні формул
/// на тисячі рядків. Знімок вантажить <c>IRegistrySnapshotLoader</c> (RT-22)
/// один раз на прогін, і він спільний для всіх прив'язок цього прогону.
///
/// ⚠ Звідси вимоги до реалізацій:
/// <list type="bullet">
/// <item><b>незмінний після завантаження</b> — читання з кількох потоків безпечне
/// без блокувань (той самий принцип, що дерево в кеші розбору, `CAL-05`);</item>
/// <item><b>видимість уже застосована</b>: у знімку лише записи, видимі на дату
/// знімка (<c>!IsDeleted</c>, вікно дії містить дату, батько композиції
/// видимий). Рушій видимості не перевіряє — він її не знає;</item>
/// <item><b>коди порівнюються без урахування регістру</b>
/// (<see cref="StringComparer.OrdinalIgnoreCase"/>), як коди полів у
/// <c>RegistryFieldSnapshotLoader</c> і коди таблиць у <c>ReferenceResolver</c>.</item>
/// </list>
///
/// ⚠ Посилання на запис (<c>EntryRef</c>) у рантаймі — ЧИСЛО, id запису: той
/// самий вибір, що вже діє для <c>Lookup</c>-комірок (§5.3). Тому всі методи
/// нижче приймають і повертають <see cref="long"/>, а не окремий тип.
///
/// ⚠ Набір методів — рівно те, що називає §5.4/§5.7: повний перегляд, пошук за
/// первинним ключем, індекс <c>(Lookup-поле, ціль)</c> і значення поля.
/// Індексний шлях <c>REGONE</c> за довільним (не первинним) ключем — розширення
/// кроків RT-20a/b, коли він знадобиться: інтерфейс новий, реалізацій дві
/// (<c>Ecr.TestKit</c> і <c>Ecr.Application</c>), і дописати метод дешевше, ніж
/// вгадувати його форму зараз.
/// </remarks>
public interface IRegistrySnapshot
{
    /// <summary>
    /// Видимі записи довідника в порядку <c>(Ordinal, Id)</c> — повний перегляд
    /// для <c>REGONE</c> і агрегатів.
    /// </summary>
    /// <param name="registryCode">Код довідника (рядковий літерал виразу).</param>
    /// <returns>
    /// Записи; порожній список — довідник є, записів немає (агрегат над ним має
    /// визначений результат, §5.4). <c>null</c> — довідника в знімку немає: опис
    /// змінили після публікації, функція дає <c>#REF</c>.
    /// </returns>
    /// <remarks>
    /// ⛔ Порядок — частина контракту, а не зручність: «перша помилка» агрегату
    /// (§5.4) мусить бути тією самою в кожному прогоні.
    /// </remarks>
    public IReadOnlyList<long>? GetEntries(string registryCode);

    /// <summary>
    /// Записи за <b>первинним</b> ключем — для <c>REGFIND</c>.
    /// </summary>
    /// <param name="registryCode">Код довідника.</param>
    /// <param name="keyParts">
    /// Частини ключа в порядку <c>Ordinal</c> полів ключа. Без первинного ключа —
    /// одна частина, <c>Code</c> запису. Нормалізує частини (§4.2) реалізація, а не
    /// рушій: правило нормалізації одне на запис і на пошук.
    /// </param>
    /// <returns>
    /// Порожній список — не знайдено (<c>#N/A</c>); один запис — знайдено; більше
    /// одного — лише за пошкоджених даних (<c>#MULTI</c>). <c>null</c> — довідника
    /// немає або кількість частин не збігається з ключем (опис змінили після
    /// публікації) — <c>#REF</c>.
    /// </returns>
    /// <remarks>
    /// ⚠ Частина <c>null</c> сюди не доходить: <c>REGFIND</c> з порожньою частиною
    /// дає <c>null</c> ще до пошуку (§5.4).
    /// </remarks>
    public IReadOnlyList<long>? FindByPrimaryKey(string registryCode, IReadOnlyList<ExpressionValue> keyParts);

    /// <summary>
    /// Записи довідника, чиє <c>Lookup</c>-поле вказує на заданий запис, у порядку
    /// <c>(Ordinal, Id)</c> — індексний шлях агрегатів для фільтра
    /// <c>ROW.&lt;Lookup&gt; = &lt;вираз без ROW&gt;</c> (§5.4).
    /// </summary>
    /// <param name="registryCode">Код довідника, рядки якого перебираються.</param>
    /// <param name="lookupFieldCode">Код <c>Lookup</c>-поля цього довідника.</param>
    /// <param name="targetEntryId">Запис, на який поле має вказувати.</param>
    /// <returns>
    /// Записи (можливо, порожньо); <c>null</c> — довідника чи поля немає, або поле
    /// не <c>Lookup</c> — <c>#REF</c>.
    /// </returns>
    /// <remarks>
    /// ⛔ Результат мусить збігатися з повним переглядом за тією самою умовою —
    /// індекс лише прискорює, а не змінює відповідь. Порядок той самий, що в
    /// <see cref="GetEntries"/>, інакше перша помилка агрегату залежала б від
    /// шляху виконання.
    /// </remarks>
    public IReadOnlyList<long>? FindReferencing(string registryCode, string lookupFieldCode, long targetEntryId);

    /// <summary>Значення поля запису — один крок шляху <c>ROW.a.b</c> чи <c>REGFIELD</c>.</summary>
    /// <param name="entryId">Запис (видимий у знімку).</param>
    /// <param name="fieldCode">Код поля.</param>
    /// <returns>
    /// Значення типу поля (§5.3): <c>Int</c>/<c>Decimal</c> → число, <c>String</c>
    /// → текст, <c>Bool</c> → булеве, <c>Date</c> → дата, <c>Lookup</c> → число
    /// (id цільового запису), <c>Unit</c> → текст (код одиниці). Незаповнене поле
    /// → <c>null</c> (<c>R-11</c>). Поля немає, або запис невидимий на дату знімка
    /// (у тому числі ціль <c>Lookup</c>, закрита раніше) → <c>#REF</c>.
    /// </returns>
    /// <remarks>
    /// ⚠ <c>#REF</c>, а не <c>null</c>, для невидимого запису — свідомо (§5.4):
    /// тихо підставити «порожньо» замість закритого запису гірше, ніж показати
    /// помилку.
    /// </remarks>
    public ExpressionValue GetField(long entryId, string fieldCode);
}
