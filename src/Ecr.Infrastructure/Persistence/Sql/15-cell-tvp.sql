-- -----------------------------------------------------------------------------
-- doc.CellValueTvp — джерело `MERGE doc.CellValue`.
--
-- ⛔ PRIMARY KEY (PeriodKey, TableRowId, ColumnDefId) — не прикраса і не
-- «щоб було». Два наслідки, кожен потрібен:
--
--   1. Кластерний ключ ТОЧНО збігається з ключем `doc.CellValue`, тож рядки
--      приїжджають на сервер уже відсортованими в порядку цільового індексу.
--      Без цього `MERGE` на 30 000 рядків або сортує їх сам, або бере
--      по одному — на найгарячішій таблиці системи.
--   2. Дублікат адреси в батчі падає ГУЧНО (2627), а не тихо. Раніше дублікат
--      усередині чанка валив `MERGE` помилкою 8672 («attempted to UPDATE or
--      DELETE the same row more than once»), але дублікат, розведений МЕЖЕЮ
--      ЧАНКА, проходив як два послідовні записи — тобто поведінка залежала від
--      того, на якій позиції в батчі опинилася комірка. Тепер батч один, і
--      відповідь на дублікат одна.
--
-- ⛔ `ValueString nvarchar(max)`, хоча стовпець — `nvarchar(1000)`. Це НЕ
-- недогляд і НЕ розширення межі: межа лишається на стовпці, задовге значення
-- впирається в неї на вставці й падає помилкою усічення. Причина рівно
-- зворотна — `nvarchar(1000)` ТУТ повернув би `DAT-03`: `SqlMetaData` з
-- оголошеною довжиною ОБРІЗАЄ довше значення на клієнті (`SqlMetaData.Adjust`),
-- тобто СУБД отримала б законні 1000 символів і мовчки їх зберегла. Той самий
-- механізм, що вже одного разу зробив утрату даних тихою через
-- `SqlParameter.Size`, і те саме рішення, що в
-- `NormalizedCellStore.AddNullable(string)`: без стелі на клієнті — гучна
-- відмова від СУБД замість огризка в базі.
--
-- ⚠ На сталість плану це не впливає: текст запиту від значень не залежить
-- узагалі, а неявна конверсія `nvarchar(max)` → `nvarchar(1000)` відбувається
-- на вставці вже відібраних рядків, не в пошуку.
-- -----------------------------------------------------------------------------
IF TYPE_ID(N'doc.CellValueTvp') IS NULL
    EXEC(N'
CREATE TYPE doc.CellValueTvp AS TABLE
(
    PeriodKey            int            NOT NULL,
    TableRowId           bigint         NOT NULL,
    ColumnDefId          int            NOT NULL,
    TableDefId           int            NOT NULL,
    ValueString          nvarchar(max)  NULL,
    ValueNumeric         decimal(28,10) NULL,
    ValueDate            datetime2(3)   NULL,
    ValueBool            bit            NULL,
    ValueRegistryEntryId int            NULL,
    ValueUnitId          int            NULL,
    IsCalculated         bit            NOT NULL,
    IsEmpty              bit            NOT NULL,
    PRIMARY KEY (PeriodKey, TableRowId, ColumnDefId)
);');
GO

-- -----------------------------------------------------------------------------
-- aud.CellChangeTvp — джерело `INSERT INTO aud.CellChange` (`WR-08`, частина
-- «запис через TVP у тій самій транзакції»).
--
-- ⛔ БЕЗ первинного ключа, і це не забудькуватість. Журнал аудиту — потік
-- подій, а не набір станів: та сама комірка може змінитися двічі в межах
-- одного батчу (правка й перерахунок), і обидва рядки мусять лягти. Ключ
-- (ChangedAt, TableRowId, ColumnDefId) відкинув би другий, тобто аудит
-- мовчки втрачав би зміни — рівно те, проти чого він існує.
--
-- ⚠ Ціна відсутності ключа тут нульова: `INSERT … SELECT` із табличного
-- параметра порядку не потребує, а `aud.CellChange` має власний кластерний
-- ключ (ChangedAt, Id) і власну схему партиціонування.
--
-- ⛔ `OldValue`/`NewValue` — `nvarchar(max)` із тієї ж причини, що
-- `ValueString` вище, і ціна помилки тут ВИЩА: комірку можна перечитати, а
-- неправдивий рядок аудиту нічим не спростуєш. Стовпці лишаються
-- `nvarchar(1000)`, задовге значення валить батч на сервері (2628) —
-- дослівно те, що описує `DAT-03`.
--
-- ⚠ `RowKey`/`Origin`/`CorrelationId`, навпаки, оголошені ТОЧНО як стовпці:
-- у них межу стереже код (`AuditWriter.EnsureFits`) ще до того, як значення
-- дійде до `SqlDataRecord`, тож тихого обрізання бути не може, а точний тип
-- знімає неявну конверсію.
-- -----------------------------------------------------------------------------
IF TYPE_ID(N'aud.CellChangeTvp') IS NULL
    EXEC(N'
CREATE TYPE aud.CellChangeTvp AS TABLE
(
    ChangedAt       datetime2(3)   NOT NULL,
    PeriodKey       int            NOT NULL,
    DocumentId      bigint         NOT NULL,
    TableRowId      bigint         NOT NULL,
    RowKey          nvarchar(100)  NOT NULL,
    ColumnDefId     int            NOT NULL,
    OldValue        nvarchar(max)  NULL,
    NewValue        nvarchar(max)  NULL,
    ChangedByUserId int            NOT NULL,
    Origin          nvarchar(32)   NOT NULL,
    IsLateEdit      bit            NOT NULL,
    CorrelationId   nvarchar(64)   NULL
);');
GO
