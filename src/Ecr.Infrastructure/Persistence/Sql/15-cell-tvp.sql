-- 15-cell-tvp.sql — табличні типи гарячого шляху запису (`WR-02`).
--
-- Навіщо. До цього `NormalizedCellStore` слав по 12 параметрів на комірку в
-- списку `VALUES`, а `AuditWriter` — по 12 на рядок журналу. Наслідків два, і
-- обидва виміряні:
--
--   1. ТЕКСТ запиту залежав від КІЛЬКОСТІ рядків у батчі, тож кожен розмір
--      чанка компілював власний план. Лінійка `MS-01` §3.2 після `WR-01`:
--      сім планів `MERGE doc.CellValue` у кеші — по одному на розмір батчу.
--   2. Стеля 2100 параметрів на запит змушувала різати батч на чанки по 100
--      комірок: вставка 500×60 = 30 000 комірок давала 300 ПОСЛІДОВНИХ
--      `MERGE` в одній транзакції (і ~200 `INSERT` аудиту чанками по 150).
--
-- Табличний параметр знімає обидва: текст запиту сталий незалежно від розміру
-- батчу (один план назавжди), а параметр рівно один (межа 2100 не діє).
--
-- ⚠ Скрипт, а не міграція EF, бо цих типів немає в моделі EF — рівно як
-- `aud.*` (`Q-049`) і `sys_ecr.*`. Перелік і порядок виконання — у
-- `setup-dev-db.ps1`, `deploy-ecr.ps1`, `verify-sql-scripts.ps1`,
-- `br07-load-test.ps1` і `SqlServerFixture.BuildSchemaAsync`; у перших трьох є
-- сторож «скрипт є в дереві, але не виконується».
--
-- ⚠ Йде ПІСЛЯ міграцій (схема `doc`) і ПІСЛЯ `11-audit-tables.sql` (схема
-- `aud`): обидві мають існувати на момент `CREATE TYPE`.
--
-- ⛔ Типи КОЛОНОК мусять збігатися з цільовими стовпцями точно. Інакше
-- SQL Server додає неявну конверсію — і план, заради сталості якого все це
-- робиться, знову залежить від того, що приїхало. Числа взяті з
-- `CellValueConfiguration.cs` (28,10 і `datetime2(3)`) і з
-- `11-audit-tables.sql`, а не «на око».
--
-- ⛔ ДВА винятки з цього правила, обидва свідомі, обидва названі нижче:
-- `ValueString`, `OldValue`, `NewValue` оголошені `nvarchar(max)`, хоча
-- стовпці — `nvarchar(1000)`. Причина — `DAT-03`, і вона детально розписана
-- біля кожного типу.
--
-- Ідемпотентний: усе під `IF TYPE_ID(...) IS NULL`.
--
-- ⚠ Табличний тип НЕ МОЖНА змінити (`ALTER TYPE` для табличних типів не
-- існує), а `DROP TYPE` не пройде, доки на тип посилається хоч одна процедура
-- чи функція. Змінити форму = новий скрипт із `DROP` + `CREATE`, а не правка
-- цього. Сьогодні на типи не посилається нічого, крім коду застосунку, тож
-- ціна такої зміни — один рядок у новому скрипті.
-- =============================================================================

SET NOCOUNT ON;
SET XACT_ABORT ON;
