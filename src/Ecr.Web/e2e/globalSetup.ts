/**
 * Сторож стенда: набір у браузері або виконується, або ПАДАЄ.
 *
 * ⛔ До цього файла `npm run test:e2e` без стенда виходив **кодом 0**,
 * виконавши 3 прогони з 20. Три `describe` гейтувалися на `ECR_E2E_PERIOD`
 * через `test.skip`, і відсутність стенда читалася як успіх. Ціна відома і
 * записана: генератор даних передавав Windows-ідентифікатор часового поясу
 * після того, як домен став вимагати IANA (`tools/Ecr.DataGen/Program.cs`),
 * стенд падав на першому кроці — і ЖОДЕН прогін у браузері не виконався
 * жодного разу протягом дня, доки прилад показував зелене.
 *
 * ⛔ Перевірка стоїть саме тут, а не в кожному файлі. Гейт усередині
 * `describe` — це копія, якої наступний доданий файл не отримає, і набір
 * мовчки повернеться в той самий стан. `globalSetup` виконується один раз для
 * ВСЬОГО набору: пропустити його не можна, додавши файл, — лише свідомо
 * назвавши змінну нижче.
 *
 * ⚠ Свідомий пропуск лишився і має ім'я: `ECR_E2E_OPTIONAL`. З ним набір не
 * падає, а прогони, яким потрібен вхід, пропускаються власними `test.skip`;
 * лишається `cellStates.spec.ts`, якому стенд і не потрібен (`/_kitchen-sink`
 * працює до входу). Це вхід для того, хто МІРЯЄ комірки на своїй машині, а не
 * для конвеєра: у конвеєрі крок «Прогони в браузері» не виконується взагалі
 * (`ci.yml`, рядок `ci-exempt`), і зробити його зеленим цією змінною нікому не
 * спаде на думку — вона нічого не приховує, вона лише не падає.
 *
 * ⚠ Параметрів у функції немає навмисно: `FullConfig` тут не потрібен, а
 * `noUnusedParameters` у `tsconfig.json` завалив би оголошений і невживаний.
 */
export default function requireStand(): void {
  // ⚠ Порожній рядок дорівнює відсутності: стенд передає ключ періоду через
  // оточення, і `ECR_E2E_PERIOD=` (порожній) означає рівно те саме, що й
  // невизначена змінна, — стенда немає.
  if ((process.env['ECR_E2E_PERIOD'] ?? '') !== '') return;

  if ((process.env['ECR_E2E_OPTIONAL'] ?? '') !== '') {
    // ⚠ Не мовчимо навіть при свідомому пропуску: рядок у виводі — єдине, що
    // відрізняє «прогнав із стендом» від «прогнав без нього» в чужому журналі.
    console.warn(
      'e2e: стенда немає, ECR_E2E_OPTIONAL заданий — прогони, яким потрібен ' +
        'вхід, будуть пропущені. Це НЕ доказ того, що вони проходять.',
    );
    return;
  }

  throw new Error(
    'Стенд не піднятий: в оточенні немає ECR_E2E_PERIOD.\n' +
      '  Запускайте набір через  powershell -File tools/e2e-stand.ps1  — він створює\n' +
      '  тимчасову базу, піднімає застосунок, заводить двох користувачів і сам кличе\n' +
      '  Playwright з потрібним оточенням.\n' +
      '  Свідомо прогнати те, чому стенд не потрібен (cellStates.spec.ts):\n' +
      '  ECR_E2E_OPTIONAL=1 npm run test:e2e',
  );
}
