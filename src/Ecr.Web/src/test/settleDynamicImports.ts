import { afterAll, vi } from 'vitest';

/**
 * AN-162: файл тестів не завершується, доки не осіли розпочаті `import()`.
 *
 * ⚠ Причина. Продукт вантажить чанки «вогнем і забути»: `void loadDocumentActionBar()` у
 * `DocumentPage.tsx` (і так само `PeriodPicker`), `lazy()`-компоненти, що почали вантажитись, але тест
 * їх не дочекався. Vitest наприкінці файлу чекає лише ТІ запити модулів, що вже в польоті
 * (`rpcDone`), а потім відхиляє решту. Якщо ланцюг статичних імпортів лінивого модуля встигне
 * попросити наступний модуль між цими двома кроками — `EnvironmentTeardownError: Cannot load
 * '…/DocumentToolbar.tsx' imported from …/DocumentActionBar.tsx after the environment was torn down`,
 * хоча всі тести зелені (CI 42898560254, `a11y (dark)`). На швидкій машині вікно не влучається, на
 * завантаженому раннері — влучається.
 *
 * ⛔ Не ретраї й не глушіння необроблених помилок: тут файл просто дочікується, доки
 * `vi.dynamicImportSettled()` не побачить жодного необчисленого модуля (він обходить і вкладені
 * статичні імпорти). Механізм загальний — новий `lazy()`/`void import()` не поверне падіння.
 *
 * ⚠ Ціна — час осідання вже розпочатих чанків (у jsdom це мілісекунди). Модуль, що НІКОЛИ не
 * дообчислюється, тепер дасть видимий таймаут `afterAll`, а не тиху гонку.
 */
afterAll(async () => {
  await vi.dynamicImportSettled();
});
