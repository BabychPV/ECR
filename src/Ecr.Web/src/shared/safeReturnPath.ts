/**
 * Куди повернути людину після входу: `from` з адреси входу, але ЛИШЕ
 * внутрішній шлях застосунку, інакше `/`.
 *
 * ⛔ Захист від відкритого редиректу: `//evil.com` і `/\evil.com` браузер
 * читає як адресу іншого хоста, а `https://evil.com` — це взагалі інша схема.
 * Приймається тільки рядок, що починається з одного `/`, за яким не йде ні `/`,
 * ні `\`, і без керівних символів (браузер їх вирізає, і `/\t/evil.com`
 * перетворився б на `//evil.com`).
 */
export function safeReturnPath(from: string | null): string {
  if (from === null || !from.startsWith('/')) return '/';
  if (from.length > 1 && (from[1] === '/' || from[1] === '\\')) return '/';
  // Коди, а не регулярний вираз: керівні символи в джерелі легко загубити.
  if ([...from].some((ch) => ch.charCodeAt(0) < 0x20 || ch.charCodeAt(0) === 0x7f)) return '/';
  return from;
}
