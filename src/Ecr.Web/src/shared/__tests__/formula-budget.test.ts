import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { evaluate, format } from '@/shared/formula/evaluate';

/**
 * Чому клієнтський обчислювач НЕ має бюджету кроків — і що станеться, якщо
 * підстава зникне.
 *
 * ⛔ Серверний обчислювач бюджет має: `Evaluator.MaxEvaluationSteps = 20 000`,
 * і заведений він не з обережності, а із заміру — вираз із тридцяти
 * предикатних агрегатів над таблицею на 471 рядок (найважча таблиця чинного
 * `.xlsm`) обчислювався **16 820 мс і 5 368 МБ** (`02b` §6.5,
 * `EvaluationBudgetTests`). Природне продовження — «дай те саме клієнтові,
 * щоб редактор не підвисав». Замір каже, що давати нічого:
 *
 * 1. **Даних у клієнта немає взагалі.** Те, що робить вираз дорогим на
 *    сервері, — читання рядків таблиці. Клієнт посилань на комірки не
 *    резолвить (`evaluate.ts`, `parsePrimary` → `#NAME`), і `[` навіть не
 *    лексується. Той самий вираз на 1587 символів коштує тут **0.3 мс** і дає
 *    `#NAME` — див. перший тест.
 * 2. **Ціна лінійна за довжиною тексту.** Заміряно на цій збірці
 *    (Node 24, vitest 5): 4 000 символів — 2.5 мс, 100 000 — 41 мс,
 *    400 000 — 152 мс, 1 000 000 — 431 мс. Ніякої квадратичності, якою
 *    зростає серверний випадок, у граматиці без даних немає.
 * 3. **Межа сервера з боку клієнта недосяжна вдесятеро** — це доводить пара
 *    тестів навколо `budgetEdge` у спільній фікстурі: тут і в
 *    `ClientServerEquivalenceTests` на сервері.
 *
 * ⚠ Тому робота тут — не захист, а СТОРОЖ: кожне з трьох тверджень записане
 * тестом, який почервоніє, коли твердження перестане бути правдою. Бюджет,
 * доданий «про всяк випадок», був би гіршим за його відсутність: він мусив би
 * спрацьовувати рівно там, де спрацьовує серверний, інакше підказка показала б
 * число там, де в документ поїде `#BUDGET`.
 */

interface BudgetEdge {
  readonly prefix: string;
  readonly repeat: string;
  readonly separator: string;
  readonly times: number;
  readonly suffix: string;
  readonly chars: number;
  readonly expected: string;
}

const fixture = resolve(
  __dirname,
  '../../../../../tests/Ecr.TestKit/Fixtures/expression-equivalence.json',
);

const budgetEdge = (JSON.parse(readFileSync(fixture, 'utf-8')) as { budgetEdge: BudgetEdge })
  .budgetEdge;

/** Вираз і час його обчислення в мілісекундах. */
function measure(expression: string): { value: string; ms: number } {
  const started = performance.now();
  const value = evaluate(expression);

  return { value: format(value), ms: performance.now() - started };
}

function repeatJoined(part: string, times: number, separator: string): string {
  return Array.from({ length: times }, () => part).join(separator);
}

describe('Клієнтському обчислювачу бюджет кроків не потрібен', () => {
  it('найважчий серверний вираз коштує клієнту мілісекунди — бо даних у нього немає', () => {
    // ⛔ Дослівно той вираз, заради якого заведено серверний бюджет
    // (`EvaluationBudgetTests.Тридцять_предикатних_агрегатів_…`): на сервері
    // над таблицею на 471 рядок він дає `#BUDGET` після 16.8 с роботи.
    const aggregate = "SUM([Items].[WHERE [WasteType] = 'W-01'].[Amount])";
    const heavy = repeatJoined(aggregate, 30, ' + ');

    // Довжина звіряється з тією, що названа на сервері: якщо форма виразу
    // колись зміниться, тест має сказати це прямо, а не мовчки міряти інше.
    expect(heavy.length).toBe(1587);

    const { value, ms } = measure(heavy);

    // ⛔ ГОЛОВНЕ ТВЕРДЖЕННЯ цього тесту — не час, а ПРИЧИНА: `#NAME` означає,
    // що клієнт до даних не дійшов і дійти не може. Саме вона робить бюджет
    // непотрібним. Якщо клієнта колись навчать резолвити посилання, цей рядок
    // почервоніє — і питання про бюджет доведеться відкрити заново, бо разом
    // із даними повернеться і квадратичне зростання.
    expect(value).toBe('#NAME');

    // Час — другорядне підтвердження (замір: 0.3 мс). Поріг щедрий навмисно:
    // на завантаженому агенті CI пауза збирача сміття не має валити тест.
    expect(ms).toBeLessThan(1000);
  });

  it('жодна форма посилання на комірку на клієнті не резолвиться', () => {
    // ⚠ Три форми, якими сервер читає дані, — по одній на кожен спосіб
    // дістатися рядків таблиці. Поки всі три дають `#NAME`, дорожчати
    // клієнтському обчислювачу нема від чого.
    expect(format(evaluate('[Amount]'))).toBe('#NAME');
    expect(format(evaluate('SUM([Items].[r0000:r0470].[Amount])'))).toBe('#NAME');
    expect(format(evaluate("SUM([Items].[WHERE [WasteType] = 'W-01'].[Amount])"))).toBe('#NAME');
  });

  it('ціна лінійна за довжиною тексту: 400 000 символів — сотні мілісекунд, не хвилини', () => {
    // ⛔ Саме цей тест має ЗУБИ проти майбутньої квадратичності — єдиної
    // форми, якою обчислювач без даних міг би стати заважким. Розрахунок
    // порога: 2 000 символів коштують 2.5 мс; якби ціна стала квадратичною,
    // 400 000 символів (у 200 разів більше) коштували б 2.5 × 200² ≈ 100 000 мс,
    // тобто сто секунд. Лінійна ціна — 152 мс (замір). Поріг 5 000 мс лежить
    // між ними з відривом у 33 рази від виміряного і в 20 разів від
    // квадратичного: ні мигати, ні пропускати регресію він не може.
    const terms = 200_000;
    const long = repeatJoined('1', terms, '+');

    expect(long.length).toBe(399_999);

    const { value, ms } = measure(long);

    // Результат перевіряється теж: «швидко, бо зламалось і вийшло на першому
    // символі» зробило б поріг зеленим без жодної роботи.
    expect(value).toBe(String(terms));
    expect(ms).toBeLessThan(5000);
  });

  it('найдорожчий вираз у межах довжини сервера рахується цілком і швидко', () => {
    // ⚠ Половина спільного доказу: друга половина — той самий `budgetEdge`
    // у `ClientServerEquivalenceTests` на сервері, де міряються ВИТРАЧЕНІ
    // КРОКИ. Разом вони кажуть: у точці, найближчій до серверної межі з боку
    // клієнта, клієнт дає число, сервер дає ТЕ САМЕ число, і бюджет сервера
    // витрачено менш ніж на двадцяту.
    //
    // ⛔ Чому форма саме `SUM(1,1,…)`, а не щільніше `1+1+…`, і що це ховає —
    // пояснено у `$comment` самої фікстури. Коротко: плаский ланцюг `+` на
    // 1000 доданків переповнює стек СЕРВЕРНОГО обчислювача, і це окремий
    // дефект, а не питання бюджету.
    const expression =
      budgetEdge.prefix +
      repeatJoined(budgetEdge.repeat, budgetEdge.times, budgetEdge.separator) +
      budgetEdge.suffix;

    // ⛔ Побудова звіряється з фікстурою по довжині: якби клієнт і сервер
    // зібрали з тих самих полів різний текст, вони міряли б різні вирази —
    // і «узгодженість» доводили б про два різні випадки.
    expect(expression.length).toBe(budgetEdge.chars);

    const { value, ms } = measure(expression);

    expect(value).toBe(budgetEdge.expected);
    expect(ms).toBeLessThan(1000);
  });
});
