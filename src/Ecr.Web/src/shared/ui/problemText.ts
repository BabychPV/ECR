import { EcrApiError } from '@/api/client';
import { t } from '@/shared/i18n';

/**
 * Що з відмови сервера МОЖНА показати людині.
 *
 * ⛔ Рішення людини: «українську прибрати — має бути залежно від обраної
 * мови». Мов у продукті три (`D-95`: en, ru, kz), української серед них
 * немає взагалі — а серверні речення писалися нею.
 *
 * ⛔ **Ключ розрізнення — розширення `messageKey`, а не мова тексту.**
 * Визначати мову рядка евристикою (кирилиця? довжина?) означало б вгадувати:
 * російський каталожний текст теж кирилицею, а казахський — тим паче.
 * Сервер натомість каже прямо: якщо у відповіді є `messageKey`, то `detail`
 * УЖЕ зібраний із каталогу мовою користувача (`ExceptionHandlingMiddleware
 * .ResolveGenericMessageAsync`), і його можна показувати. Якщо `messageKey`
 * немає — `detail` сирий, написаний розробником, і його показувати не можна.
 *
 * ⚠ Станом на 2026-09-20 таких «каталожних» кидків 63 — головні шляхи (вхід,
 * блокування, зміна пароля, доступ до документа, подання/погодження/
 * відхилення/повернення, створення документа й рядка, періоди, 500-та).
 * Решта ~382 переводяться фоном, і до того часу вони просто втрачають
 * подробицю, а не показують чужу мову.
 *
 * ⚠ `title` показується ЗАВЖДИ: він і так із каталогу, це гарантує
 * серверний сторож `ErrorTitleCatalogTests`. Тобто користувач ніколи не
 * лишається без назви проблеми — втрачається лише конкретика там, де її ще
 * не переклали.
 */
export interface ProblemText {
  /** Назва проблеми — завжди з каталогу, завжди показується. */
  readonly title: string;

  /**
   * Подробиця, яку МОЖНА показати: локалізована сервером.
   *
   * ⚠ `null` означає «подробиця є, але чужою мовою» АБО «подробиці немає» —
   * і для екрана це одне й те саме: показувати нічого.
   */
  readonly detail: string | null;

  /** Стабільний код відмови; `null` — помилка не від нашого API. */
  readonly code: string | null;

  /** Ідентифікатор кореляції для підтримки; `null` — те саме. */
  readonly correlationId: string | null;

  /**
   * Сире серверне речення, яке ми НЕ показали.
   *
   * ⛔ Не для екрана. Існує, щоб подробиця не зникала безслідно: розробник
   * бачить її в діагностиці, а користувач — ні.
   */
  readonly suppressed: string | null;
}

/**
 * Чи можна показати `detail` людині.
 *
 * Два випадки, і обидва — перевірювана властивість, а не здогад про мову:
 *
 * 1. **`messageKey` у відповіді.** Сервер зібрав `detail` із каталогу мовою
 *    користувача (`ExceptionHandlingMiddleware.ResolveGenericMessageAsync`).
 *
 * 2. **`status === 0` — відмову склав САМ КЛІЄНТ**, відповіді HTTP не було
 *    взагалі (`RenderErrorScreen`: зламаний рендер, застарілий чанк). Їхній
 *    текст англійський і написаний ЛІТЕРАЛОМ навмисно: саме в цих випадках
 *    каталог може бути недоступний, і звернення до нього дало б `⟦…⟧` замість
 *    пояснення (розбір — у коментарі `RenderErrorScreen.tsx`). Ховати їх
 *    означало б лишити «екран не показався» без жодної технічної подробиці —
 *    рівно те, проти чого написаний той компонент.
 *
 * ⛔ `status === 0` — не хитрий прапорець, а єдина властивість, якою
 * клієнтська відмова відрізняється від серверної: у неї немає коду
 * відповіді, бо немає й самої відповіді.
 */
function mayShowDetail(error: EcrApiError): boolean {
  if (error.problem.status === 0) return true;

  const key = error.problem.extensions2?.['messageKey'];

  return typeof key === 'string' && key.length > 0;
}

/**
 * Заголовок, який прийшов КЛЮЧЕМ, а не текстом.
 *
 * ⛔ Один такий випадок є, і він не помилка: `401` без тіла народжується на
 * КЛІЄНТІ (`api/client.ts`, редирект на вхід), а `shared/i18n` сам імпортує
 * `apiFetchIfChanged` із того ж файлу — виклик `t()` там замкнув би цикл
 * модулів. Тому клієнт кладе ключ, а розв'язує його шар показу.
 *
 * ⚠ Форма ключа перевіряється РЕГУЛЯРКОЮ, а не спробою `t()`: відсутній ключ
 * `t()` повертає позначеним (`⟦…⟧`), тож «спробувати й подивитись» зробило б
 * із будь-якого людського заголовка позначений ключ на екрані. Заголовки
 * сервера — речення з пробілами, під цю форму не підпадають.
 */
const CatalogKey = /^err\.[A-Za-z0-9.-]+$/;

function titleOf(problem: EcrApiError['problem']): string {
  return CatalogKey.test(problem.title) ? t(problem.title) : problem.title;
}

/**
 * Розбирає відмову на те, що показати, і те, що сховати.
 *
 * ⚠ Одна функція на всі три подачі (`ErrorAlert`, `AsyncBoundary`,
 * `showApiError`). Три копії цього правила означали б, що в одній із них
 * рано чи пізно лишиться голий `error.message` — і саме там українська
 * доживе до продакшену.
 */
export function problemText(error: unknown): ProblemText {
  if (!(error instanceof EcrApiError)) {
    /*
     * ⚠ Не `String(error)` на екран: сюди потрапляє все, що не є нашою
     * відмовою, — `TypeError`, помилка мережі, текст із чужої бібліотеки.
     * Жодне з цього не перекладене й не призначене людині.
     */
    return {
      title: t('state.errorTitle'),
      detail: null,
      code: null,
      correlationId: null,
      suppressed: error === null || error === undefined ? null : String(error),
    };
  }

  const raw = error.problem.detail ?? null;
  const fromCatalog = mayShowDetail(error);

  return {
    title: titleOf(error.problem),
    detail: fromCatalog ? raw : null,
    code: error.problem.errorCode,
    correlationId: error.problem.correlationId,
    suppressed: fromCatalog ? null : raw,
  };
}

/**
 * Кладе сховану подробицю в діагностику.
 *
 * ⛔ `console.debug`, а не `warn`/`error`: це не поломка, а очікуваний стан
 * переходу — сервер ще не переклав цей кидок. Рівень `warn` привчив би
 * ігнорувати попередження, яких сотні.
 *
 * ⚠ Викликається зі сторони ПОКАЗУ, а не з `problemText`: чиста функція, яку
 * можна спокійно кликати в рендері, не має писати в консоль на кожен
 * перемалюв.
 */
export function logSuppressedDetail(shown: ProblemText): void {
  if (shown.suppressed === null) return;

  // ⚠ Без `eslint-disable`: правила `no-console` в конфігу немає, і
  // придушення, яке нічого не придушує, лише псує лічильник придушень
  // (`shared/__tests__/lintRules.test.ts` стежить за їх кількістю).
  console.debug('[ecr] подробицю відмови не показано (немає messageKey):', {
    code: shown.code,
    correlationId: shown.correlationId,
    detail: shown.suppressed,
  });
}
