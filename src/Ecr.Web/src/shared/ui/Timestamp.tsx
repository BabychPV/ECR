import type { JSX } from 'react';
import { formatDate, formatDateTime } from '@/shared/format';

/**
 * Момент часу на екрані (`D15-09`).
 *
 * ⛔ **Чому це компонент, а не виклик `formatDateTime()` на місці.** Модуль
 * `shared/format` існує від початку, протестований — і на 2026-09-19 не мав
 * ЖОДНОГО продуктового споживача: усі сімнадцять місць, де дата з сервера
 * доходить до екрана, друкували сирий рядок ISO (`2026-09-19T18:51:58.275`).
 * Тобто самої лише наявності функції виявилося недосить; те саме вже сталося
 * зі статусами, доки не з'явився `StatusBadge`.
 *
 * ⛔ **Точність не втрачається.** Головний аргумент за сирий ISO записаний у
 * `JobsPage` («той самий сирий ISO, що в журналі аудиту»), і він слушний:
 * журнал аудиту — доказ, а доказ мусить бути однозначним і придатним до
 * копіювання. Тому видимий текст читабельний, а ТОЧНЕ значення лишається в
 * розмітці: `<time dateTime="…">` — машинозчитуване поле стандарту, плюс
 * `title` для наведення. Нічого не зникає, змінюється лише те, що бачить око.
 *
 * ⚠ `<time>`, а не `<span title>`: атрибут `title` читалки озвучують
 * непослідовно, а `dateTime` — частина семантики елемента, і її видно в DOM
 * без наведення (тобто й у тесті, і при копіюванні розмітки).
 */
export interface TimestampProps {
  /** Момент, як його віддав сервер (ISO-рядок), або `null`. */
  readonly value: string | null | undefined;

  /**
   * Показати лише дату, без години.
   *
   * ⚠ Для полів, які СЕРВЕР віддає календарною датою (`validFrom`,
   * `effectiveFrom`, `startsAt`): показувати в них годину означало б
   * приписати їй точність, якої в даних немає.
   */
  readonly dateOnly?: boolean | undefined;

  /**
   * Що показати, коли моменту немає.
   *
   * ⚠ Дефолт — тире, а не порожнеча: порожня комірка таблиці читається
   * двояко («немає» чи «не завантажилось»), і це вже окремо ловили на
   * `DocumentsPage` (UI-walkthrough F6).
   */
  readonly fallback?: string | undefined;

  /**
   * Показати СЕКУНДИ.
   *
   * ⛔ Заведено не «про всяк випадок». Дефолт — `timeStyle: 'short'`, тобто
   * без секунд, і для «коли задача почалася» чи «коли застосунок піднявся»
   * цього досить. Але є колонки, де секунда — це сама суть даних: мітки
   * телеметрії в перегляді мапінгу (`MappingRows`) відрізняються між собою
   * саме секундами, і без них два різні виміри виглядають однаково. Показати
   * їх однаково означало б сховати те, заради чого на цю таблицю й дивляться.
   *
   * ⚠ Не вмикати там, де секунди нічого не додають: зайва точність на екрані
   * читається як важливість і змушує вчитуватися в число, яке не має змісту.
   */
  readonly precise?: boolean | undefined;
}

/** Момент часу: читабельно на екрані, точно — в розмітці. */
export function Timestamp({
  value,
  dateOnly = false,
  fallback = '—',
  precise = false,
}: TimestampProps): JSX.Element {
  if (value === null || value === undefined || value === '') {
    return <span data-timestamp="none">{fallback}</span>;
  }

  const shown = dateOnly
    ? formatDate(value)
    : formatDateTime(value, precise ? { dateStyle: 'medium', timeStyle: 'medium' } : undefined);

  /*
   * ⛔ Нерозібраний рядок показується ЯК Є, а не тире й не порожнеча.
   * `formatDate` на такому повертає порожній рядок (`Nothing`), і сховати це
   * за тире означало б, що зіпсоване значення сервера виглядає точно так
   * само, як відсутнє. Видно сире — видно й те, що з ним щось не так.
   */
  if (shown === '') {
    return <span data-timestamp="unparsed">{value}</span>;
  }

  return (
    <time dateTime={value} title={value} data-timestamp="ok">
      {shown}
    </time>
  );
}
