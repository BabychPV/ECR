import type { JSX } from 'react';

/**
 * Фірмовий знак — монограма `E` з трьох смуг, тобто рядків звіту.
 * Рішення людини від 2026-09-17 (варіант «Б»).
 *
 * ⛔ Пропорції підібрані під НАЙМЕНШИЙ розмір, а не під найбільший. У
 * першому начерку три смуги на 16 px зливалися в три однакові риски й
 * знак переставав читатися як `E`. Виправлено трьома важелями разом:
 * середня смуга помітно коротша (55% проти 100%), проміжок між смугами
 * дорівнює їхній товщині (а не половині), і середня смуга має власний
 * відтінок. Кожен важіль окремо недостатній — при 16 px працює лише
 * сукупність.
 *
 * ⚠ Кольори НЕ літерали: `currentColor` для крайніх смуг і
 * `--mantine-color-brand-4` для середньої. Тому знак сам стає світлим у
 * темній темі й темним у світлій, і заміна палітри його не зачепить —
 * та сама вимога єдиного джерела, що й для решти теми (`ФВ-14.11`).
 *
 * ⚠ `aria-hidden`: поруч у шапці стоїть текстове «ECR Web», тож для
 * зчитувача екрана знак — оздоба. Дубльована назва читалася б двічі.
 */
export function BrandMark({ size = 22 }: { size?: number }): JSX.Element {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      aria-hidden="true"
      focusable="false"
    >
      <rect x="3" y="4.5" width="18" height="4" rx="1.5" fill="currentColor" />
      <rect
        x="3"
        y="10"
        width="10"
        height="4"
        rx="1.5"
        fill="var(--mantine-color-brand-4)"
      />
      <rect x="3" y="15.5" width="18" height="4" rx="1.5" fill="currentColor" />
    </svg>
  );
}
