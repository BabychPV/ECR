import type { ReactNode } from 'react';

/**
 * Типи таблиці переліку (`KIT.md` §6.5, директива №15 §2, Шар 3).
 *
 * ⛔ Окремим файлом від `DataTable.tsx` навмисно: `FilterBar` і майбутній
 * `ListPage` описують колонки, не монтуючи саму таблицю, а імпорт заради
 * одного типу притяг би за собою Mantine `Table` і `ScrollArea` в чанк, де
 * жодної таблиці немає (`D-132` — бюджет маршруту 250 КБ, найтісніший уже за
 * 245.6).
 */

/** Напрямок сортування. */
export type SortDirection = 'asc' | 'desc';

/** Що зараз відсортовано; `null` — порядок такий, як прийшов із сервера. */
export interface SortState {
  readonly key: string;
  readonly direction: SortDirection;
}

/** Одне скалярне значення, за яким колонка порівнюється. */
export type SortScalar = string | number | boolean | null | undefined;

/**
 * Значення, за яким колонка порівнюється: скаляр або кортеж скалярів.
 *
 * ⚠ Кортеж порівнюється поелементно — перший елемент, за рівності другий і
 * так далі. Він потрібен там, де колонка групує рядки, а всередині групи
 * порядок задає інше поле (розмірність → код одиниці): склеювати два поля
 * в один рядок означало б покластися на те, як колатор ставить роздільник, а
 * керівні символи `Intl.Collator` пропускає зовсім.
 */
export type SortKey = SortScalar | readonly SortScalar[];

/**
 * Колонка таблиці (`KIT.md` §6.5).
 *
 * ⚠ `label` приходить ПРОПОМ, а не з каталогу за похідним ключем: набір не
 * знає, як цей екран називає своє поле, і вигадати ключ `table.<key>` означало
 * б показати читалці `⟦table.code⟧` на кожному переліку (`D-138`). Викликач
 * передає готовий `t('documents.key')` — рівно так, як це вже робить
 * `PageHeader.back.label`.
 */
export interface DataTableColumn<Row> {
  /** Ідентифікатор колонки: ключ сортування і ключ React. */
  readonly key: string;

  /** Підпис у шапці. Готовий рядок інтерфейсу, не ключ каталогу. */
  readonly label: string;

  /**
   * Числова колонка — ВЕЛИЧИНА: праворуч, моноширинним, числове сортування
   * десяткових рядків і форматування локаллю (роздільники розрядів, дріб до
   * `CellFractionCeiling` знаків) (`KIT.md` §6.5 `num`).
   *
   * ⚠ Вирівнювання праворуч — не оздоблення: у стовпчику чисел різної
   * довжини лише воно дає змогу порівняти порядки величин очима.
   *
   * ⛔ Лише `num` вмикає форматування числа. Поле-`number` колонки БЕЗ `num`
   * малюється як є (`String`): ідентифікатор `1234` на екрані `1,234` — це
   * число, якого в базі немає й за яким нічого не знайти. Лічильник, якому
   * потрібні роздільники розрядів, мусить сказати `num` явно.
   */
  readonly num?: boolean | undefined;

  /**
   * Показати значення числової колонки ТОЧНО таким, яким воно прийшло: без
   * округлення, без роздільників розрядів, без локального десяткового знака.
   * Має сенс лише разом із `num` — вирівнювання, моноширинність і числове
   * сортування лишаються від нього.
   *
   * ⛔ Для колонок, де кожен знак — це і є відповідь (множник одиниці
   * `0.4535923700`): округлення до трьох знаків стерло б його в `0.454`.
   * Рядок із API показується дослівно, включно з масштабом колонки
   * (`'0.5000000000'`), бо саме заради цих знаків `decimal` їде рядком
   * (`e470777a`); `number` — через `String`, без `Intl`.
   *
   * ⚠ Дефолт `num` (три знаки) цим НЕ змінюється — це відкрите рішення, і
   * колонка відмовляється від нього поіменно, а не всі разом.
   */
  readonly exact?: boolean | undefined;

  /** Моноширинний текст без вирівнювання праворуч (коди, ключі). */
  readonly mono?: boolean | undefined;

  /**
   * Чи можна сортувати за цією колонкою. Дефолт — так.
   *
   * ⚠ `false` ставлять там, де порядок не визначений: колонка з кнопками дій
   * або з вузлом, у якого немає скалярного значення.
   */
  readonly sortable?: boolean | undefined;

  /**
   * Значення для порівняння, якщо клітинка малює не його.
   *
   * ⛔ Без цього сортування колонки, яку малює `render`, порівнювало б
   * `undefined` з `undefined` — тобто мовчки не робило б нічого. Саме тому
   * `sortable` за замовчуванням увімкнене лише там, де значення ДІСТАЄТЬСЯ:
   * `sortValue`, або поле `row[key]`.
   */
  readonly sortValue?: ((row: Row) => SortKey) | undefined;

  /** Вміст клітинки. Без нього береться поле `row[key]`. */
  readonly render?: ((row: Row) => ReactNode) | undefined;

  /** Мінімальна ширина. ⚠ Саме мінімальна (`ФВ-14.30`): довший переклад росте. */
  readonly minWidth?: number | string | undefined;

  /** Підказка при наведенні на шапку. */
  readonly title?: string | undefined;
}

/**
 * Межа `L5`: таблиця переліку — не більше семи колонок, решта — у шухляді
 * рядка (`KIT.md` §1.7, директива №15 §0).
 */
export const MaxColumns = 7;
