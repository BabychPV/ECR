import { useCallback, useState } from 'react';

/**
 * Значення поля вводу, яке належить САМОМУ полю, доки людина в ньому друкує.
 *
 * ⛔ Правило (живий стенд, 2026-09-24, `drop-repro.mjs`): введене в поле —
 * джерело правди для поля, поки воно у фокусі. Адреса сторінки, відкладений
 * фільтр, автовибір — ПОХІДНІ від поля й ніколи не пишуть у нього, поки
 * людина друкує.
 *
 * Чому це не дрібниця. Поле, КЕРОВАНЕ значенням з адреси (`value={urlValue}`),
 * губить символи: react-router застосовує навігацію переходом (`startTransition`),
 * тобто адреса оновлюється ПІЗНІШЕ за подію вводу. React тим часом повертає
 * керованому полю старий `value` — і наступна клавіша лягає поверх старого
 * значення. Набір `R12345` у «Row key» при сповільненому в 4× процесорі давав
 * у полі `"R"` чи `"5"` (5 з 5 спроб); «Rule» — `"C3"`, `"S3"`. Автовибір
 * періоду, що дописав `202609` у щойно очищене поле, дав `202608202609`.
 *
 * Як працює:
 *  - `value` — локальний стан поля; `setValue` змінює лише його (запис у
 *    адресу/фільтр викликач робить сам, поруч);
 *  - зовнішнє значення (`external`) приймається в поле, лише коли воно
 *    СПРАВДІ змінилося і поле НЕ у фокусі — тобто змінилося ззовні:
 *    навігація, «Назад», кнопка скидання (клік переносить фокус на кнопку);
 *  - поки поле у фокусі, зовнішнє значення ігнорується повністю: відлуння
 *    власного набору з адреси запізнюється й несе СТАРШЕ значення.
 *
 * ⚠ Blur НЕ підтягує зовнішнє значення: адреса в цю мить ще може нести
 * запізніле відлуння (людина набрала й одразу натиснула Tab), і підтягнути
 * його означало б стерти останні символи рівно тим дефектом, який тут
 * виправлено. Наступна справжня зміна ззовні однаково прийметься.
 *
 * ⚠ Без ефекту синхронізації: зовнішнє значення порівнюється під час рендеру
 * (патерн «adjusting state when a prop changes» з документації React), тож
 * поле не малює кадр зі старим значенням.
 */
export interface FieldDraft<T> {
  /** Що показує поле. */
  readonly value: T;

  /** Змінити значення поля (лише поля — не адреси). */
  readonly setValue: (value: T) => void;

  /** Чи поле зараз у фокусі. */
  readonly focused: boolean;

  /** Обробники фокусу — розгорнути на поле вводу. */
  readonly onFocus: () => void;
  readonly onBlur: () => void;
}

export function useFieldDraft<T>(external: T): FieldDraft<T> {
  const [value, setValue] = useState<T>(external);
  const [seen, setSeen] = useState<T>(external);
  const [focused, setFocused] = useState(false);

  if (!Object.is(external, seen)) {
    setSeen(external);
    if (!focused) setValue(external);
  }

  const onFocus = useCallback(() => setFocused(true), []);
  const onBlur = useCallback(() => setFocused(false), []);

  return { value, setValue, focused, onFocus, onBlur };
}
