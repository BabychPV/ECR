import { useSyncExternalStore } from 'react';
import { catalogSnapshot, subscribeCatalog } from './index';

/**
 * Підписує компонент на каталог рядків.
 *
 * ⛔ Викликається в **корені кожного піддерева, що показує написи** — тобто в
 * `LoginPage` і в `AppLayout`. Без цього виклику `t()` читає каталог рівно
 * один раз, під час першого рендера, коли його ще не завантажено: користувач
 * бачить `login.title` замість назви системи, доки щось інше випадково не
 * викличе перерендер.
 *
 * ⚠ Це не «оптимізація перекладу», а умова того, що переклад узагалі
 * з'являється. Компонентні тести цього не ловлять за побудовою: вони
 * підставляють рядки самі й ніколи не проходять шлях «порожній каталог →
 * завантажений».
 */
export function useCatalog(): number {
  // ⚠ Третій аргумент (знімок для сервера) обов'язковий у React 19 навіть без
  // SSR: без нього гідратація кинула б виняток, а не показала б неточність.
  return useSyncExternalStore(subscribeCatalog, catalogSnapshot, catalogSnapshot);
}
