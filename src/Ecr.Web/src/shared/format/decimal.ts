/**
 * Десяткові з API приїжджають РЯДКОМ — і порівнюються як числа, не як текст.
 *
 * ⛔ `Number(x) === 1` тут не годиться. `decimal(28,16)` несе 16 знаків після
 * коми, а `Number`/`JSON.parse` дають IEEE-754 з ~15–17 значущими цифрами:
 * `Number('0.1000000000000000000001') === Number('0.1')` — `true`, хоча це
 * різні числа. Саме щоб цього не сталося, сервер і перевів `decimal` у рядок
 * (`DecimalAsStringJsonConverter`, `e470777a`); прогнати його через `Number`
 * у клієнті означало б викинути рівно те, заради чого зміну робили.
 *
 * ⚠ Але й звичайна рівність рядків хибна — в інший бік: `decimal` носить
 * масштаб колонки, тож та сама одиниця приходить як `"1"`, `"1.0"` або
 * `"1.0000000000"` залежно від того, звідки її прочитали.
 */

/**
 * Канонічний вигляд десяткового рядка; `null` — це не десяткове число.
 *
 * Провідні нулі цілої частини й хвостові нулі дробової прибираються, `+`
 * відкидається, `-0` зводиться до `0`: `'+01.2300'` → `'1.23'`, `'-0.000'` →
 * `'0'`. Уся робота — на рядку, жодного `Number` по дорозі.
 *
 * ⚠ Експонента (`1e3`) свідомо НЕ приймається: `decimal.ToString` з
 * інваріантною культурою її не друкує ніколи, тож такий рядок прийшов не від
 * контракту, і вгадувати за нього — дорожче, ніж сказати «не число».
 */
export function normalizeDecimal(value: string): string | null {
  const match = /^([+-]?)(\d*)(?:\.(\d*))?$/.exec(value.trim());
  if (match === null) return null;

  const [, sign = '', rawInteger = '', rawFraction = ''] = match;

  // ⛔ Ані `''`, ані `'-'`, ані `'.'` числом не є, хоча регекс їх і пропускає.
  if (rawInteger.length === 0 && rawFraction.length === 0) return null;

  const integer = rawInteger.replace(/^0+(?=\d)/, '');
  const fraction = rawFraction.replace(/0+$/, '');
  const whole = integer.length === 0 ? '0' : integer;

  if (whole === '0' && fraction.length === 0) return '0';

  const digits = fraction.length === 0 ? whole : `${whole}.${fraction}`;
  return sign === '-' ? `-${digits}` : digits;
}

/**
 * Чи два десяткові рядки — те саме число.
 *
 * ⛔ Нерозпізнане значення не дорівнює НІЧОМУ, включно з таким самим
 * нерозпізнаним: «однакові рядки» — це не «однакові числа», і мовчазне
 * `true` на парі сміття зробило б із цієї функції ще одне місце, де хибне
 * значення виглядає правильним.
 */
export function decimalEquals(left: string, right: string): boolean {
  const a = normalizeDecimal(left);

  return a !== null && a === normalizeDecimal(right);
}
