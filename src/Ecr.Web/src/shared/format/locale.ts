import { DefaultLanguage, language, type Language } from '@/shared/i18n';

/**
 * Локаль форматування — з мови ПРОДУКТУ, не браузера (`D15-09`).
 *
 * ⛔ Це не «зручна обгортка». `toLocaleString()` без аргументів і
 * `new Intl.NumberFormat()` без локалі беруть локаль СЕРЕДОВИЩА: у браузері —
 * налаштування ОС, у Node — ICU за замовчуванням. Продукт тримає кілька мов
 * (`D-95`), і мова інтерфейсу не зобов'язана збігатися з мовою браузера:
 * користувач із англійським Chrome, що працює казахською, отримував би
 * англійський роздільник тисяч і англійський порядок дати посеред казахської
 * сторінки. Саме тому в `eslint.config.js` уже стоїть заборона на
 * `toLocale*()` без локалі — цей модуль і є те, чим її замінюють.
 */

/**
 * Внутрішній код мови → тег BCP-47.
 *
 * ⛔ Копія переліку винятків із `shared/i18n/index.ts`, і копія тут СВІДОМА, а
 * не недогляд. `languageTag()` звідти не експортовано, а розширювати публічну
 * поверхню i18n у цьому ж PR не можна (файл належить сусідній роботі). Ризик
 * розходження двох копій знятий не домовленістю, а твердженням у тесті
 * (`__tests__/locale.test.ts`, «мапа не розходиться з i18n»): воно звіряє
 * результат `formatLocale()` з `document.documentElement.lang`, який пише сам
 * i18n. Змінити мапу в одному місці й не помітити — не вийде: тест почервоніє.
 *
 * ⚠ Це перелік ВИНЯТКІВ, а не список дозволених мов. `kz` — код КРАЇНИ
 * Казахстан (ISO 3166); мова казахська в BCP-47 — `kk` (ISO 639-1). Мови
 * приходять із реєстру сервера (`Language = string`), тож четверта мова мусить
 * працювати без перезбирання клієнта.
 */
const BcpTagOverrides: Record<string, string> = { kz: 'kk' };

/**
 * Куди відкочуємось, коли тег непридатний.
 *
 * ⚠ Вибір — мова за замовчуванням продукту, а не «нейтральний» формат і не
 * виняток. Причини три:
 *   1. `t()` уже має рівно цей ланцюг запасних варіантів (мова → мова за
 *      замовчуванням → позначений ключ). Числа й дати, що падали б в інший
 *      формат, ніж текст поруч, дали б на одному екрані дві різні політики.
 *   2. «Нейтральний» формат (ISO, крапка як роздільник) — це четверта локаль,
 *      якої немає в жодній мові продукту: вона виглядала б як справжня і
 *      нікому не належала б.
 *   3. Кидок заборонений умовою задачі й по суті: рядок конфігурації не має
 *      права зносити екран. Форматування — найнижчий шар, він викликається в
 *      кожній комірці сітки.
 */
const FallbackLocale = bcpTag(DefaultLanguage);

function bcpTag(lang: Language): string {
  return BcpTagOverrides[lang] ?? lang;
}

/**
 * Пам'ять розв'язаних локалей.
 *
 * ⚠ Не мікрооптимізація: `formatLocale()` кличеться з кожної комірки сітки на
 * кожному рендері, а `supportedLocalesOf` щоразу читає дані ICU.
 */
const resolvedLocales = new Map<Language, string>();

/**
 * Тег BCP-47, яким форматувати для заданої (за замовчуванням — активної) мови.
 *
 * ⛔ Експортовано навмисно: цей же тег потрібен компонентам, що звертаються до
 * `Intl` самі (`DateInput`/`DatePickerInput` із `@mantine/dates`,
 * `Intl.Collator` для сортування колонок). Без нього вони взяли б локаль
 * середовища — тобто рівно той дефект, який `D15-09` і закриває.
 */
export function formatLocale(lang: Language = language()): string {
  const cached = resolvedLocales.get(lang);
  if (cached !== undefined) return cached;

  const value = resolveLocale(lang);
  resolvedLocales.set(lang, value);

  return value;
}

/**
 * Розв'язує тег і перевіряє його ДВІЧІ — синтаксис і підтримку.
 *
 * ⛔ Перевірок саме дві, бо відмови дві різні, і небезпечніша — та, що НЕ
 * кидає. Заміряно на V8 (Node 24.19):
 *   • `new Intl.NumberFormat('')` / `('en_US')` / `('*')` → `RangeError`.
 *     Це помітно: сторінка зникає, стек показує винного.
 *   • `new Intl.NumberFormat('kz')` / `('xx-YY')` → НЕ кидає. `kz`
 *     синтаксично правильний тег BCP-47 (дволітерний підтег мови), просто
 *     невідомий ICU, тож `Intl` МОВЧКИ бере локаль середовища: `resolvedOptions()
 *     .locale` віддає `en-US`. Тобто казахський інтерфейс отримав би
 *     англійські числа й дати — той самий дефект `D15-09`, лише через інші
 *     двері й без жодного сліду в консолі.
 *
 * Тому `supportedLocalesOf` — не «додаткова строгість», а єдиний спосіб
 * відрізнити «ICU вміє цю мову» від «ICU тихо підставив свою». Він же ловить і
 * синтаксичні відмови (кидає той самий `RangeError`), тому обидві перевірки
 * вміщаються в один `try`.
 *
 * ⚠ Зонд саме `Intl.NumberFormat`: усі три конструктори (`NumberFormat`,
 * `DateTimeFormat`, `PluralRules`) живляться з однієї бази ICU, тож окремі
 * зонди дали б три однакові відповіді ціною трьох звернень. Якщо колись
 * розійдуться — це буде видно як падіння тесту на конкретній функції, а не як
 * тихий інший формат.
 */
function resolveLocale(lang: Language): string {
  const tag = bcpTag(lang);

  try {
    if (Intl.NumberFormat.supportedLocalesOf(tag).length > 0) return tag;
  } catch {
    // Тег непридатний синтаксично — нижче загальний відкат.
  }

  return FallbackLocale;
}
