import { MutationCache, QueryClient } from '@tanstack/react-query';
import { applySliceCachePolicy } from '@/features/grid/sliceCache';
import { showApiError } from '@/shared/ui/notify';

/**
 * Кеш запитів застосунку і страхувальна сітка під ВСІ зміни (`UI-00`).
 *
 * ⛔ Що саме стереже `MutationCache.onError`. Дія, яка не вдалася і про яку
 * нікому не сказали, — найдорожчий різновид дефекту в цій системі: оператор
 * натиснув «Подати», сервер відмовив (період закрито, маршрут не містить його
 * ролі), екран не змінився — і людина впевнена, що звіт подано. Наступний, хто
 * про це дізнається, — інспектор.
 *
 * ⚠ Але сітка НЕ прикриває дірку, яка є сьогодні: я порахував — усі 80 викликів
 * `useMutation(` у `src` уже мають власний `onError`. Тобто вона ловить нуль
 * випадків у цій ревізії, і це чесна причина її завести: зараз інваріант
 * тримається домовленістю, яка діє рівно доти, доки про неї пам'ятають. 81-й
 * виклик, написаний без `onError`, з нею не оніміє.
 *
 * ⛔ Саме тому сітка мовчить, коли зміна обробляє відмову сама. Інакше кожна з
 * 80 показувала б ДВА тости на одну відмову — а це гірше за відсутність сітки:
 * подвоєне сповіщення привчає його закривати не читаючи.
 */
export function createQueryClient(): QueryClient {
  const client = new QueryClient({
    mutationCache: new MutationCache({
      onError: (error, _variables, _context, mutation) => {
        /*
         * ⚠ Ознака — оголошений `onError` самої зміни, а не прапорець у `meta`.
         * Прапорець довелося б проставити у 80 місцях, і забути його в 81-му
         * так само легко, як забути сам `onError`: ознака має випливати з
         * коду, а не з дисципліни.
         */
        if (mutation.options.onError !== undefined) return;

        showApiError(error);
      },
    }),
    defaultOptions: {
      queries: {
        // Дані звітності змінюються рідко, але помилково показати застаріле — дорого
        staleTime: 30_000,
        retry: (failureCount, error) => {
          // Не повторювати 4xx: 403 і 422 повторення не виправить
          const status = (error as { problem?: { status: number } })?.problem?.status;
          if (status !== undefined && status >= 400 && status < 500) return false;
          return failureCount < 2;
        },
      },
    },
  });

  /**
   * Політика кешу для зрізів таблиць (`CL-02`, `DIRECTIVE-14-ARCH.md` §3.5).
   *
   * ⛔ `refetchOnWindowFocus` за замовчуванням увімкнений, і на цьому екрані він
   * коштує дорожче, ніж будь-де: оператор звіряє числа з Excel, повертається до
   * вкладки через 31 с — і КОЖЕН змонтований зріз (до 91 на аркуші)
   * перезапитується одночасно найважчим запитом системи. За ті 31 с у
   * документі, який він сам і тримає відкритим, не змінилося нічого.
   *
   * ⚠ `staleTime` 5 хв замість глобальних 30 с — про те саме: зріз змінюють
   * рівно три події (власне збереження, імпорт, перерахунок), і кожна з них уже
   * ЯВНО інвалідує кеш (`sliceCache.ts`). Час тут нічого не стереже.
   *
   * ⚠ `setQueryDefaults`, а не опції в `useQuery`: `DocumentGrid.tsx` у цьому
   * пакеті недоторканний (рядок плану `D14-12`), а дефолти за префіксом ключа —
   * штатний механізм TanStack Query і діють на всі зрізи одразу, включно з тими,
   * що з'являться пізніше.
   */
  applySliceCachePolicy(client);

  return client;
}
