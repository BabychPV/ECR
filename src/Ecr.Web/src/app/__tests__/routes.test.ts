import { readFileSync } from 'node:fs';
import path from 'node:path';
import { describe, it, expect } from 'vitest';
import { Routes } from '../../../e2e/routes';

/**
 * Сторож дрейфу маршрутів (`D-142`).
 *
 * ⛔ Перевірка жила в `e2e/screenshots.spec.ts` усередині `describe`,
 * гейтованого на `ECR_E2E_PERIOD`, і тому не виконувалася НІДЕ: ані локально
 * (`npm run test:e2e` без стенда пропускав увесь блок), ані в конвеєрі (крок
 * «Прогони в браузері» виведений із нього як `ci-exempt`). Її власний коментар
 * називав це «перевіркою, яка виглядає повною і такою не є» — і описував себе.
 *
 * ⛔ Тут вона тому, що стенд їй НЕ ПОТРІБЕН: ані браузера, ані бази, ані
 * застосунку — лише два файли на диску. Місце перевірки визначає не те, що
 * вона стереже, а те, що їй потрібно для роботи; лишити її в Playwright
 * означало б прив'язати дешеву перевірку до найдорожчого прогону в дереві й
 * знову не виконувати її ніколи. Під vitest вона йде в кожному `npm run test`
 * і в кожному прогоні конвеєра (крок «Тести клієнта»).
 *
 * ⚠ Перелік знімків імпортується з `e2e/routes.ts`, а не переписується сюди.
 * Копія зробила б сторожа безглуздим: він стеріг би свій список, а знімки
 * знімали б інший, і розбіжність між ними ніхто не побачив би.
 *
 * ⚠ Роутер читається ТЕКСТОМ, а не імпортується. `createBrowserRouter`
 * викликається на рівні модуля і тягне `AppLayout` з усім, що той імпортує;
 * сторож маршрутів падав би тоді від будь-якої несумісності в чужому
 * компоненті — а перевірка, яка червоніє не зі своєї причини, живе до третього
 * такого падіння.
 */
const router = readFileSync(path.resolve(process.cwd(), 'src/app/router.tsx'), 'utf8');

/** Шляхи, оголошені в роутері, у тому ж вигляді, що й у переліку знімків. */
const declared = [...router.matchAll(/path:\s*'([^']+)'/g)]
  .map((m) => (m[1] ?? '').replace(/^\//, ''))

  // ⛔ Поза переліком навмисно: вхід і зміна пароля живуть ДО сесії, а каталог
  // компонентів існує лише в розробці (`D7-09`) — знімати сторінку, якої немає
  // у виробничій збірці, означало б класти в артефакти те, чого замовник не
  // побачить ніколи.
  .filter((p) => p !== 'login' && p !== 'change-password' && !p.startsWith('_'))
  .filter((p) => !p.includes(':'));

// `index: true` для кореня описаний окремо і в перелік шляхів не потрапляє —
// тому мінус один не потрібен, але корінь у нашому переліку є.
const covered = new Set(Routes.map((r) => r.path.replace(/^\//, '')));

describe('Перелік маршрутів для знімків (D-142)', () => {
  it('перелік маршрутів не відстав від роутера', () => {
    const missing = declared.filter((p) => !covered.has(p));

    expect(missing, 'ці маршрути оголошені в роутері й не потрапляють у знімки').toEqual([]);
  });

  it('у переліку немає маршрутів, яких у роутері вже немає', () => {
    // ⛔ Другий бік тієї самої звірки, і він же — перевірка САМОГО сторожа.
    // Регулярний вираз на перейменованому чи переписаному `router.tsx` дав би
    // порожній `declared`, тобто «розбіжностей немає»: сторож ставав би
    // зеленим рівно тоді, коли перестав щось стерегти. Мовчазний нуль такого
    // самого роду і привів цю перевірку сюди з Playwright.
    //
    // ⚠ Наслідок для знімків реальний: адреса, вилучена з роутера, лишається в
    // переліку, прогін іде на неї й падає на «немає заголовка» — тобто на
    // симптомі, а не на причині.
    const stale = [...covered].filter((p) => !declared.includes(p));

    expect(stale, 'ці адреси є в переліку знімків, але роутер їх більше не знає').toEqual([]);
  });
});
