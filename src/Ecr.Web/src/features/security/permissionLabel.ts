import { tOr } from '@/shared/i18n';

/**
 * Людська назва права — і код, який лишається на екрані (`U-11`).
 *
 * ⛔ Матриця прав `/admin/security` підписувала 41 колонку сирим кодом
 * (`Calculation.EditConstant`, `System.ManageLocalization`). Це той самий клас
 * «код сервера як текст на екрані», який уже знято з `TemplatesPage` (#437),
 * бейджів зрізу й версії звіту (#438), `ValidationPanel`/`ExpressionsPage`/
 * `PeriodsPage` (#440) і `MethodologyVersionsPage` (#441): код не є текстом
 * інтерфейсу, він не перекладається, а продукт тримає три мови (`D-95`).
 * Спосіб той самий, що там, — ключ каталогу, а не власна таблиця в компоненті.
 *
 * ⚠ Але тут є різниця з тими чотирма, і вона свідома: код **не ховається**.
 * Адміністратор безпеки оперує саме кодами — вони стоять у `09-seed.sql`, у
 * журналі `DangerousPermissionsGranted`, у відмовах `ECR-AUTH-0403
 * (Requires permission {permission})` і в шаблонах складених ролей
 * (`Report.%`). Прибрати код означало б змусити його щоразу здогадуватись, яка
 * саме назва відповідає тому, що написано в журналі. Тому — `TwoLine`
 * (`KIT.md` §1.7: «людські підписи замість кодів, код приглушено другим
 * рядком»), той самий примітив, яким це вже зроблено на інших переліках.
 *
 * ⛔ Запасний варіант — САМ КОД, а не `⟦permission.…⟧`. Каталог прав приходить
 * із сервера, і завтра там буде 42-ге право; ключа під нього в `09-seed.sql`
 * ще не буде. `t()` намалював би на місці зрозумілого коду незрозумілу
 * позначку — тобто погіршив би екран рівно в той момент, коли на ньому
 * з'явилося щось нове. Перевірено окремим тестом (`permissionLabel.test.ts`).
 */

/** Ключ каталогу під назву права. Код записаний так, як його називає сервер. */
export function permissionLabelKey(code: string): string {
  return `permission.${code}`;
}

/** Назва права мовою інтерфейсу; немає рядка в каталозі — сам код. */
export function permissionLabel(code: string): string {
  return tOr(permissionLabelKey(code), code);
}
