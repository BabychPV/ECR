import type { ColumnDto } from '@/api/types';
import { normalizeDecimal } from '@/shared/format';
// ⚠ Глибокий імпорт рівно на одну функцію, і це названо, а не сховано:
// `formatDecimal` з'явився в `shared/format/number.ts` цією ж роботою, а
// дописати його в бар'єл (`shared/format/index.ts`) не можна — файл поза
// переліком дозволених на запис, бо його того ж дня правила сусідня сесія.
// Правило теки дотримано по суті: `Intl` лишився всередині `shared/format`,
// сюди приходить готова функція. Рядок у бар'єл — перший пункт «далі».
import { formatDecimal } from '@/shared/format/number';

/**
 * Значення комірки, коли `decimal` приходить РЯДКОМ (коміт `e470777a`).
 *
 * ⛔ Що саме зламалося й чому компілятор мовчить. `RowDto.cells` типізовані як
 * `{ [key: string]: unknown }` — контракт навмисно не обіцяє типу, бо тип
 * комірки задає КОЛОНКА, а не схема. Тому перехід `decimal` з JSON-числа на
 * JSON-рядок не дає ЖОДНОЇ помилки `tsc`: усе, що раніше отримувало `5`, тепер
 * отримує `"5.0000000000"` і компілюється так само. Наслідки — рантаймні.
 *
 * ⛔ Канон десяткового рядка сюди ІМПОРТУЄТЬСЯ (`shared/format/decimal.ts`,
 * `d9e75a82`), а не пишеться вдруге. Другий нормалізатор поруч із першим
 * розійшовся б із ним, і розходження двох копій одного правила — це рівно той
 * клас дефектів, який цей перехід і виправляє.
 *
 * ⚠ Модуль ЧИСТИЙ: рівність значень і формат показу не залежать від сітки, а
 * сітка в jsdom важка. Перевіряються вони без жодного рендера.
 */

/**
 * Десятковий канон для значення комірки, яке типізоване як `unknown`.
 *
 * ⚠ `normalizeDecimal` приймає рядок — і правильно робить, бо описує ДРІТ. Але
 * в комірці законно лежить і число: `Int` та `Lookup` їдуть числами й після
 * переходу, а старіший сервер міг прислати число й для `decimal`. Зведення
 * `number` → рядок робиться тут, в одному місці, а не в кожному викликачі.
 */
function decimalOf(value: unknown): string | null {
  if (typeof value === 'string') return normalizeDecimal(value);

  // ⚠ `String(1e-7)` дає `'1e-7'`, і `normalizeDecimal` таке свідомо відхиляє
  // (`decimal.ToString` інваріантною культурою експоненти не друкує). Отже
  // відповідь буде `null` — «не десяткове», і викликач покаже значення як є.
  // Це не втрата: до переходу сітка малювала рівно `String(value)`.
  if (typeof value === 'number' && Number.isFinite(value)) return normalizeDecimal(String(value));

  return null;
}

/**
 * Чи два значення комірки — ОДНЕ І ТЕ САМЕ значення.
 *
 * ⛔ Порівняння ЗНАЧЕННЯ, не тексту й не посилання. `5`, `'5'` і
 * `'5.0000000000'` — одне число, записане трьома способами, і всі три
 * приходять у цю систему легально: перше — колонки `Int`/`Lookup` та старіший
 * сервер, друге — те, що клієнт щойно надіслав, третє — те, що сервер повернув
 * у масштабі колонки. Текстове порівняння відповіло б «різні» на всі три пари,
 * і тоді «змінилося / не змінилося» означало б «змінилося» ЗАВЖДИ: комірка
 * отримувала б позначку незбереженої правки на порожньому місці й не втрачала
 * б її ніколи.
 *
 * ⚠ `null` і `undefined` зведені: «ключа немає» і «ключ зі значенням `null`»
 * різняться в контракті (`R-B4`), але не в питанні «чи змінилося значення» —
 * цю різницю несе окремий прапорець `isEmpty`, а не сама рівність.
 *
 * ⚠ Нечислові значення порівнюються `Object.is`: рядок, булеве і дата — це
 * рівно те, чим вони приїхали, і жодної нормалізації вони не потребують.
 */
export function sameCellValue(left: unknown, right: unknown): boolean {
  const a = left ?? null;
  const b = right ?? null;

  if (a === null || b === null) return a === b;

  const decimalA = decimalOf(a);
  const decimalB = decimalOf(b);

  // ⛔ «Одне число, друге ні» — це РІЗНІ значення, а не привід порівняти їх
  // текстом: `'н/д'` і `0` не мають ставати однаковими через `String()`.
  if (decimalA !== null || decimalB !== null) return decimalA === decimalB;

  return Object.is(a, b);
}

/**
 * Значення комірки для МАШИНИ: буфер обміну, перелік у діалозі, журнал.
 *
 * ⛔ Не `formatDecimal`: тут не можна ні групувати розряди, ні міняти
 * десятковий роздільник. Ctrl+C віддає текст, який Excel має прочитати назад
 * як число, а `1 234,5` він в en-локалі прочитає як текст — тобто копія
 * перестала б бути копією.
 *
 * ⚠ Але й не `String(value)`: після переходу на рядок це віддавало б у буфер
 * `5.0000000000` замість `5` — формально те саме число, фактично десять зайвих
 * нулів у кожній комірці аркуша замовника.
 */
export function cellText(value: unknown): string {
  if (value === null || value === undefined) return '';

  return decimalOf(value) ?? String(value);
}

/**
 * Типи колонок, чиє значення показується як ЧИСЛО.
 *
 * ⚠ `Formula` і `Calculated` тут поруч із `Decimal` навмисно: їхній результат —
 * той самий `decimal`, що приїжджає тим самим рядком. Помилки вони не додають:
 * значення, яке не є десятковим, `cellDisplay` віддає текстом як є.
 */
const NumericColumnTypes: ReadonlySet<string> = new Set(['Decimal', 'Formula', 'Calculated']);

/** Чи показувати значення цієї колонки як число (для `cellTemplate` сітки). */
export function isNumericColumn(column: ColumnDto): boolean {
  return NumericColumnTypes.has(column.dataType);
}

/**
 * Що оператор бачить у комірці.
 *
 * ⛔ Повертає `''` для порожньої комірки — не `'0'`. «Не заповнювали» і «нуль»
 * різняться у звіті регулятора, і показати друге замість першого дорожче за
 * будь-яку зручність.
 *
 * ⚠ Локаль — продукту (`shared/format`), і другого правила тут не заводиться:
 * `en` → `1,234.5`, `ru`/`kk` → `1 234,5`.
 *
 * ⚠ Нечислове значення в числовій колонці показується ТЕКСТОМ як є. Так у
 * сітку потрапляє те, що `coerce()` не розпізнало як число (`'н/д'`): сервер
 * відповість `ECR-CELL-0422`, і до того моменту оператор має бачити саме те,
 * що ввів, а не порожню комірку.
 */
export function cellDisplay(value: unknown, column: ColumnDto): string {
  if (value === null || value === undefined) return '';
  if (!isNumericColumn(column)) return String(value);

  return formatDecimal(value, undefined, undefined, displayScaleOf(column)) ?? String(value);
}

/**
 * Скільки знаків після коми ПОКАЗУВАТИ щонайменше — формат комірки, як у Excel:
 * `1.5` при `scale = 4` → `1.5000`.
 *
 * ⛔ Лише показ. Значення в рядку, редактор, `pendingStore`, тіло PATCH і буфер
 * (`cellText`) нулів не отримують — вони йдуть від сирого значення, не від
 * цього шаблону.
 *
 * ⚠ Колонка без масштабу — 0, тобто без доповнення, як до цієї зміни.
 * Довший дріб не зрізається: округлення — справа `roundToScale` на вводі.
 */
function displayScaleOf(column: ColumnDto): number {
  const scale = column.scale;

  return typeof scale === 'number' && Number.isInteger(scale) && scale > 0 ? scale : 0;
}
