import { describe, it, expect } from 'vitest';
import type { ColumnDto } from '@/api/types';
import { roundToScale } from '../rounding';

/**
 * ⛔ Усі очікування нижче ПОРАХОВАНІ ВРУЧНУ за правилом
 * `decimal.Round(x, scale, MidpointRounding.AwayFromZero)` — тим самим, яким
 * сервер вирішує, приймати комірку чи відповісти `ECR-CELL-0422`
 * (`ColumnDef.Validate`, `src/Ecr.Domain/Entities/Configuration/ColumnDef.cs`).
 * Жодне з них не знято з виводу самої реалізації: інакше тест доводив би лише
 * те, що код робить те, що робить.
 */

function column(overrides: Partial<ColumnDto> = {}): ColumnDto {
  return {
    id: 1,
    code: 'volume',
    header: 'Volume',
    dataType: 'Decimal',
    ordinal: 1,
    isReadOnly: false,
    isRequired: false,
    isRequiredByMethodology: false,
    displayFormat: null,
    defaultValue: null,
    lookupRegistryDefId: null,
    unitId: null,
    unitSymbol: null,
    precision: 18,
    scale: 2,
    ...overrides,
  };
}

describe('roundToScale: масштаб 16 — те, на чому стара реалізація брехала', () => {
  it('17 знаків при scale=16 округлюються ТОЧНО, а не через 10**16', () => {
    // Вхід: 2.00000000000000005, масштаб 16. Сімнадцята цифра дробу — 5,
    // «половина від нуля» піднімає шістнадцяту: 2.0000000000000001.
    //
    // ⛔ Стара формула давала **2.0000000000000004** — не сусіднє число, а
    // промах на три одиниці останнього знака. Чому: `Number(...)` дає рівно 2,
    // `2 * 10 ** 16` = 2e16, а 2e16 більше за MAX_SAFE_INTEGER
    // (9 007 199 254 740 991) у 2.2 раза, тож крок подвійної точності там
    // дорівнює 4, а не 1. Поправка `* (1 + Number.EPSILON)` додавала
    // 2e16 * 2.22e-16 ≈ 4.44 — тобто більше за цілу одиницю, — і `Math.round`
    // повертав 20000000000000004. Нешкідлива при масштабі 2 поправка при
    // масштабі 16 САМА вигадувала знаки.
    expect(roundToScale('2.00000000000000005', column({ scale: 16 }))).toBe('2.0000000000000001');
  });

  it('ціле поза MAX_SAFE_INTEGER округлюється без зсуву на 2', () => {
    // 12345678901234567.5 при масштабі 0: половина від нуля → ...568.
    //
    // ⛔ Стара формула давала **12345678901234570**: множник дорівнює 1, але
    // саме значення (1.2e16) уже поза MAX_SAFE_INTEGER — крок там 2, —
    // і `* (1 + Number.EPSILON)` додавало ≈ 2.74, тобто більше за крок.
    // Результат розходився з сервером на 2 цілих: `decimal` жодної з цих
    // втрат не має, тож сервер побачив би «неокруглене» число.
    expect(roundToScale('12345678901234567.5', column({ scale: 0 }))).toBe('12345678901234568');
  });

  it('значення, де вже бреше сам double, не псується округленням', () => {
    // `0.1 + 0.2` у подвійній точності дорівнює 0.30000000000000004.
    // Масштаб 2: відкинуте починається з 0 → вгору не йдемо → 0.30 → «0.3».
    expect(roundToScale('0.30000000000000004', column({ scale: 2 }))).toBe('0.3');
  });
});

describe('roundToScale: правило половини — від нуля, як на сервері', () => {
  it("від'ємна половина йде ВІД нуля, а не вгору", () => {
    // ⛔ `Math.round(-2.5)` = −2 (до +∞); .NET з `AwayFromZero` = −3.
    // Розбіжність в один знак означала б, що клієнт надішле число, яке сервер
    // вважатиме неокругленим, і вставка відхилиться там, де мала пройти.
    expect(roundToScale('-2.5', column({ scale: 0 }))).toBe('-3');
    expect(roundToScale('2.5', column({ scale: 0 }))).toBe('3');
  });

  it('половина на межі подвійної точності округлюється вгору', () => {
    // `1.005 * 100` у подвійній точності дає 100.49999999999999, і саме тому
    // стара реалізація потребувала поправки на EPSILON. Рядковий шлях просто
    // бачить цифри «005»: відкинуте починається з 5 → 1.01.
    expect(roundToScale('1.005', column({ scale: 2 }))).toBe('1.01');
  });

  it('перенос проходить крізь дев’ятки', () => {
    // 9.99 при масштабі 1: відкинуте «9» → 9.9 + 0.1 = 10.0 → «10».
    expect(roundToScale('9.99', column({ scale: 1 }))).toBe('10');
  });

  it("від'ємне, що округлюється в нуль, не дає −0", () => {
    // −0.4 при масштабі 0: |0.4| вниз → 0. `decimal` від'ємного нуля не має.
    expect(roundToScale('-0.4', column({ scale: 0 }))).toBe('0');
  });

  it('звичайний зайвий знак із Excel', () => {
    // 12.3456 при масштабі 2: відкинуте «56» → вгору → 12.35.
    expect(roundToScale('12.3456', column({ scale: 2 }))).toBe('12.35');
  });
});

describe('roundToScale: експоненційний запис — ПІДТРИМАНО', () => {
  // ⚠ Рішення: показник розгортається зсувом десяткової точки (суто рядково),
  // а не відхиляється. Причина: `parseNumber` (`clipboard.ts`) експоненту вже
  // приймає, тобто `coerce` перетворить таку комірку на число й надішле її.
  // Відхилити округлення (`null`) означало б відправити НЕокруглене значення
  // й отримати `ECR-CELL-0422` рівно на головному шляху введення — Excel
  // показує великі й малі числа саме в цьому записі.

  it('1e-17 при масштабі 16 стає нулем', () => {
    // 1e-17 = 0.00000000000000001 — сімнадцятий знак. Відкинута цифра 1 < 5,
    // тож шістнадцять знаків дають 0.0000000000000000, тобто «0».
    expect(roundToScale('1e-17', column({ scale: 16 }))).toBe('0');
  });

  it('1.5E+3 — це 1500, тобто вже в масштабі', () => {
    // Розгортання дає 1500 без дробової частини; при масштабі 0 округлювати
    // нічого — `null`, і позначка «округлено» не ставиться.
    expect(roundToScale('1.5E+3', column({ scale: 0 }))).toBeNull();
  });

  it('експонента з дробовим хвостом таки округлюється', () => {
    // 1.25e1 = 12.5; масштаб 0, половина від нуля → 13.
    expect(roundToScale('1.25e1', column({ scale: 0 }))).toBe('13');
  });

  it('показник поза межами double не приймається', () => {
    // ⚠ Межа — захист пам'яті: розгортання 1e+100000 дало б сто тисяч нулів.
    expect(roundToScale('1e+100000', column({ scale: 2 }))).toBeNull();
  });
});

describe('roundToScale: null означає «нічого не змінилося»', () => {
  it('значення вже в масштабі не округлюється і не позначається', () => {
    // ⛔ `null` тут значуще: позначка ставиться ЛИШЕ на змінені комірки,
    // інакше лічильник «округлено N значень» показував би всю таблицю.
    expect(roundToScale('12.34', column({ scale: 2 }))).toBeNull();
  });

  it('хвостові нулі не рахуються за зайві знаки', () => {
    // Excel охоче дописує нулі до формату колонки. «12.3400» — те саме
    // 12.34, і позначка «округлено» на ньому була б неправдою.
    expect(roundToScale('12.3400', column({ scale: 2 }))).toBeNull();
  });

  it('колонка без масштабу не округлюється', () => {
    expect(roundToScale('12.3456', column({ scale: null }))).toBeNull();
  });

  it('нечислова колонка не округлюється', () => {
    expect(roundToScale('12.3456', column({ dataType: 'Text', scale: 2 }))).toBeNull();
  });
});

describe('roundToScale: нечисловий вхід', () => {
  it.each(['abc', '', '   ', '1.2.3', '1.2,3', 'NaN', 'Infinity', '1.', '.5', '--1', '0x10'])(
    '«%s» не число → null',
    (raw) => {
      expect(roundToScale(raw, column({ scale: 2 }))).toBeNull();
    },
  );

  it('самотня кома — це десятковий роздільник, а не сміття', () => {
    // ⛔ Відхилення від початкової постановки (там кома стояла в переліку «не
    // число»), і воно свідоме: `parseNumber` (`clipboard.ts:66`) уже перетворює
    // «1,5678» на 1.5678, тобто `coerce` вважає таку комірку числом і
    // надсилає її. Якби округлення її не впізнавало, аркуш в uk-UA (кома —
    // десятковий роздільник) отримував би `ECR-CELL-0422` на кожній комірці
    // із зайвим знаком — рівно та поломка головного шляху введення, заради
    // якої округлення взагалі існує.
    expect(roundToScale('1,5678', column({ scale: 2 }))).toBe('1.57');
  });

  it('пробіли-роздільники розрядів не заважають', () => {
    // `parseNumber` їх теж відкидає (зокрема нерозривні).
    expect(roundToScale('1 234.5678', column({ scale: 2 }))).toBe('1234.57');
  });
});
