import type { TableSliceDto } from '@/api/types';

/**
 * Чи вважати зріз таблиці порожнім (`ФВ-14.21`, `ФВ-14.22`).
 *
 * ⛔ Умова тут РІЗНА для двох різних таблиць, і саме це було дефектом:
 * `DocumentGrid` рахував порожнечу одним `columns.length === 0` на всі види
 * таблиць одразу (директива №09 `W8` п.2, `S-13`). Фіксована таблиця без
 * жодного рядка при цьому малювалася як звичайна сітка — заголовки на місці,
 * вводити нема куди, і жодного слова про те, чому. Склад рядків такої
 * таблиці задає ШАБЛОН, тож «рядків немає» — це стан даних, а не проміжок
 * роботи, і показати його треба словами.
 *
 * ⚠ Для динамічної таблиці нуль рядків — НОРМА: саме з нього оператор і
 * починає, натиснувши «Додати рядок». Показати їй порожній стан означало б
 * сховати ту єдину кнопку, якою її наповнюють, — тобто зробити таблицю
 * назавжди порожньою через повідомлення про порожнечу.
 *
 * ⚠ Питання «чи додає рядки оператор» — відповідь ДОМЕНУ (`allowsDynamicRows`
 * приходить із сервера), а не `RowMode`, складений на клієнті: друге
 * визначення того самого правила вже одного разу розійшлося саме з собою
 * всередині сервера (`A7-41`).
 *
 * @param slice Завантажений зріз.
 * @param allowsDynamicRows Чи додає рядки оператор.
 */
export function isSliceEmpty(slice: TableSliceDto, allowsDynamicRows: boolean): boolean {
  if (slice.columns.length === 0) {
    return true;
  }

  return !allowsDynamicRows && slice.rows.length === 0;
}

/**
 * Чи порожнеча зрізу спричинена саме відсутністю колонок.
 *
 * ⚠ Від цього залежить ТЕКСТ порожнього стану: «немає колонок» і «немає
 * рядків» лікуються по-різному, і однаковий напис на обидва випадки відсилав
 * би адміністратора шукати не те.
 */
export function isMissingColumns(slice: TableSliceDto | undefined): boolean {
  return slice === undefined || slice.columns.length === 0;
}
