import { describe, it, expect } from 'vitest';
import { decimalDelta } from '@/features/audit/changeDelta';

/** UI-38: Δ рахується з рядків сховища (`decimal(34,16)`), без втрати знаків через `Number`. */
describe('decimalDelta', () => {
  it.each([
    ['53.1771000000000000', '54.2000000000000000', '1.0229'],
    ['54.2', '53.1771', '-1.0229'],
    ['10', '10.0000000000000000', '0'],
    ['-1.5', '1.5', '3'],
    ['0', '0.0000000000000001', '0.0000000000000001'],
    // ⛔ Через `Number` тут вийшло б 0.0000001 з хвостом похибки або 0 — знаки за 17-ю значущою.
    ['12345678901234567.1234567', '12345678901234567.1234568', '0.0000001'],
    ['1200.5', '200.5', '-1000'],
  ])('%s → %s = %s', (was, now, delta) => {
    expect(decimalDelta(was, now)).toBe(delta);
  });

  it.each([
    [null, '1'],
    ['1', null],
    ['abc', '1'],
    ['1', '1e5'],
  ])('не число або немає значення (%s → %s) — Δ немає', (was, now) => {
    expect(decimalDelta(was, now)).toBeNull();
  });
});
