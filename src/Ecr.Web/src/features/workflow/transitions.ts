/**
 * Переходи робочого процесу аркуша — **дзеркало домену**, не друге правило.
 *
 * ⛔ Джерело істини — `src/Ecr.Domain/Entities/Documents/ApprovalState.cs`:
 * саме там `Submit`, `Approve`, `Reject` і `Reopen` відмовляють із
 * `ECR-DOC-0409`, і саме сервер лишається тим, хто вирішує. Тут — відповідь
 * на інше питання: **яку кнопку взагалі показувати**. Кнопка «Затвердити» на
 * чернетці не помилка доступу, а обіцянка, якої стан аркуша не виконує.
 *
 * ⚠ Таблиця одна на весь клієнт і винесена з компонентів навмисно. Розкладена
 * по місцях використання, вона розійшлася б із доменом мовчки — а перевірити
 * це можна було б лише клікаючи. Сторож `Клієнтські_переходи_збігаються_з_доменом`
 * читає обидва файли і падає, щойно вони розходяться.
 *
 * ⚠ Скалярного статусу документа не існує (`D-93`): стан живе на парі
 * `аркуш × період`, і кожна дія адресує саме її.
 */

/** Стан аркуша за період; значення приходять із сервера як є. */
export type SheetState = 'Draft' | 'Submitted' | 'Approved' | 'Rejected';

/** Дія робочого процесу. */
export type WorkflowAction = 'submit' | 'approve' | 'reject' | 'reopen';

/**
 * Стани, у яких дія має сенс.
 *
 * ⛔ Це НЕ права. Право каже, чи людині взагалі можна; стан каже, чи є що
 * робити. Обидві умови потрібні, і жодна не замінює іншу: маршрут погодження
 * рахує сервер (`IAccessDecisionService.CanApproveAsync`), і клієнт його не
 * відтворює — саме тому тут немає жодної згадки про ролі.
 */
export const AllowedIn: Readonly<Record<WorkflowAction, readonly SheetState[]>> = {
  // Подати можна чернетку або відхилений аркуш — повторне подання поданого
  // перезаписало б момент і автора, на яких тримається зріз (ФВ-5.7).
  submit: ['Draft', 'Rejected'],

  // Затвердити й відхилити — лише подане.
  approve: ['Submitted'],
  reject: ['Submitted'],

  // Повернути в роботу — подане або затверджене; повторне подання створює
  // НОВИЙ зріз, старий лишається назавжди (ФВ-9.17).
  reopen: ['Submitted', 'Approved'],
};

/** Чи має сенс дія в цьому стані. */
export function isAllowed(action: WorkflowAction, state: string): boolean {
  return (AllowedIn[action] as readonly string[]).includes(state);
}

/**
 * Дії, які вимагають причини.
 *
 * ⛔ Причина обов'язкова в домені (`ECR-DOC-0422`), і питати її має інтерфейс,
 * а не відмова сервера. Відхилення без пояснення повертає роботу тому, хто не
 * знає, що виправляти, — і цикл повторюється (ФВ-5.15).
 */
export const NeedsReason: readonly WorkflowAction[] = ['reject', 'reopen'];

/** Чи потрібна причина для дії. */
export function needsReason(action: WorkflowAction): boolean {
  return NeedsReason.includes(action);
}
