/**
 * Q-274: `GET /api/v1/templates/{id}/versions` — курсорний ендпоінт
 * (Q-225), відповідь `{items, nextCursor, totalCount}`, а НЕ голий масив.
 *
 * ⛔ Компонент типізував цю відповідь як `TemplateVersionSummary[]` і читав
 * `versionQueries[index]?.data ?? []` — `.data` при пагінованій відповіді
 * НЕ `undefined`, а об'єкт-обгортка, тож `?? []` не рятував, і `.filter`
 * падав із `TypeError: ((intermediate value) ?? []).filter is not a
 * function` на КОЖНОМУ відкритті «Новий проєкт» (`src/Ecr.Web/e2e/keyboardPath.spec.ts`,
 * побічна знахідка Q-273; відтворено наживо на реальному стенді до фіксу).
 *
 * ⚠ Мокається САМЕ РЕАЛІСТИЧНА пагінована форма відповіді (об'єкт-обгортка
 * з `items`), а не голий масив — тест, який мокає голий масив, лишився б
 * зеленим і до, і після фіксу і не довів би нічого.
 */
function respond(routes: Record<string, unknown>): void {
  vi.stubGlobal(
    'fetch',
    vi.fn(async (input: RequestInfo | URL) => {
      const url = typeof input === 'string' ? input : input.toString();
      const path = url.split('?')[0] ?? url;

      const body = routes[path];
      if (body === undefined) {
        throw new Error(`Немає мока для ${url}`);
      }

      return new Response(JSON.stringify(body), {
        status: 200,
        headers: { 'Content-Type': 'application/json' },
      });
    }),
  );
}

// ⛔ Q-298 (виміряно під час верифікації): `@testing-library/react`
// реєструє ВЛАСНИЙ `afterEach(() => cleanup())` як побічний ефект самого
// імпорту (рядок 2 цього файлу) — тобто ДО того, як тут виконався б
// будь-який `vi.setConfig`: ES-модулі виконують `import` раніше решти
// коду файлу незалежно від порядку рядків у джерелі. Тому
// `vi.setConfig({ hookTimeout })`, викликаний нижче в цьому файлі, НЕ
// встигає подіяти на вже зареєстрований хук RTL — перевірено емпірично
// (падало `Hook timed out in 10000ms` навіть після `vi.setConfig`).
// Замість боротьби з порядком реєстрації хука — `show()` повертає
// результат `render()`, і кожен тест сам викликає `unmount()`
// НАПРИКІНЦІ свого тіла (у межах ВЛАСНОГО, уже обґрунтовано широкого
// таймауту тесту). Коли автоматичний `afterEach` RTL запускається, дерево
// вже розмонтоване — розмонтовувати вдруге нічого, і дефолтні 10с на
// цей хук вистачає з великим запасом.
function show() {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });

  return render(
    <MantineProvider>
      <QueryClientProvider client={client}>
        <CreateProjectModal opened onClose={() => {}} onCreated={async () => {}} />
      </QueryClientProvider>
    </MantineProvider>,
  );
}

afterEach(() => {
  vi.unstubAllGlobals();
});

