// але сам ФАЙЛ усе одно завершувався `Hook timed out in 10000ms` на рівні
// сюїти (не окремого тесту) — той самий хук авто-`cleanup` RTL, помножений
// на залишкову вартість закриття jsdom-середовища після важких дерев.
// `beforeAll` виконується ПІСЛЯ реєстрації хука RTL (побічний ефект
// імпорту), але ДО першого тесту — на відміну від виклику на верхньому
