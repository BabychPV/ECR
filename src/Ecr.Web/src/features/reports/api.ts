/**
 * Адреса вивантаження зрізу звітності в `.xlsx` (`R7`, `D-52a`).
 *
 * ⚠ Саме АДРЕСА, а не `fetch`. Автентифікація тримається на cookie, і
 * навігація тим самим походженням несе її сама — `<a href={…} download>` дає
 * файл одним запитом і лишає браузеру «зберегти як». Обгортка через `fetch` +
 * `blob:` привезла б ту саму книгу вдруге в пам'ять вкладки і зламала б ім'я
 * файлу з `Content-Disposition`. Той самий висновок уже записаний над
 * посиланням на книгу документа (`features/export/ExportButton.tsx`).
 *
 * ⚠ Вміст книги — колонки опису версії, за якою зріз побудовано; числа в ній
 * мають 15 значущих цифр, бо стільки тримає Excel (`02-contracts.md` §9).
 * Для звірки без утрат є `GET …/rows`.
 */
export function snapshotExportUrl(snapshotId: number): string {
  return `/api/v1/reports/snapshots/${snapshotId}/export.xlsx`;
}
