import type { ExpressionDialect } from '@/api/types';

/**
 * Діалект мови виразів — **параметр**, а не зашита константа (`D-113`).
 *
 * ⛔ Причина саме така, як записано у `ФВ-9.15a`: редактор обслуговує три
 * області одразу — методології, правила валідації і формули шаблону, — і
 * колись до них додасться режим C# (`K-1`). Зашитий діалект означав би, що
 * четверта область почнеться з переписування редактора.
 *
 * ⚠ Режим C# тут **відсутній, а не прихований заглушкою**: `ФВ-9.15a` вимагає
 * саме цього. Вимкнений пункт у переліку обіцяє те, чого немає, і кожен, хто
 * його побачить, спитає, коли ввімкнуть. Сам перелік діалектів приходить із
 * СЕРВЕРА (`@/api/types`): коли режим C# ухвалять, тип розшириться сам.
 */
export type { ExpressionDialect };

/**
 * Ідентифікатор мови в Monaco для діалекту.
 *
 * ⚠ Два ідентифікатори, а не один з перемикачем: Monaco тримає токенізатор
 * за ідентифікатором мови, і один спільний означав би, що відкриті поруч
 * формула шаблону і формула методології підсвічуються ОДНАКОВО — за правилами
 * того, хто зареєструвався останнім.
 */
export function languageIdOf(dialect: ExpressionDialect): string {
  return dialect === 'Template' ? 'ecr-template' : 'ecr-methodology';
}

/**
 * Чи дозволені в діалекті посилання методології — `@арг`, `CST.`, `!формула`.
 *
 * `02b` §3.4: методологія працює з підготовленими аргументами, а не лізе в
 * документ сама.
 */
export function allowsMethodologyRefs(dialect: ExpressionDialect): boolean {
  return dialect === 'Methodology';
}

/**
 * Чи дозволені в діалекті посилання на комірки документа —
 * `[Аркуш].[Таблиця].[Рядок].[Колонка]`.
 *
 * ⛔ У методології заборонені (`02b` §3.4) — і це не обмеження, а межа, яка
 * робить методологію переносною між шаблонами.
 */
export function allowsCellRefs(dialect: ExpressionDialect): boolean {
  return dialect === 'Template';
}
