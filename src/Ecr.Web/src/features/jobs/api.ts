import { useMutation, useQuery, type UseMutationResult, type UseQueryResult } from '@tanstack/react-query';
import { apiEnqueue, apiFetch, type AcceptedJob } from '@/api/client';
import type { JobSummary } from '@/api/types';
import { showApiError } from '@/shared/ui/notify';

/*
 * ⛔ Адреса записана повністю, а не збирається з помічника — той самий
 * прийом, що й `features/registries/api.ts` і `features/units/api.ts`: сторож
 * `Кожна_дія_сервера_має_споживача_в_інтерфейсі` шукає в коді клієнта літерал
 * `/api/v1/…` разом із методом поруч, і винесений префікс зробив би дію
 * «недосяжною з інтерфейсу».
 */

/** Як часто опитувати перелік, доки в ньому є незавершена задача. */
const ListPollMs = 3000;

/**
 * Адреса переліку задач.
 *
 * ⛔ `mine=true` — НЕ косметичний фільтр, а межа доступу: власні задачі видно
 * без права `System.ViewHealth`, чужі — ні (`Q-156`, `BE-08`). Тому запит без
 * нього тому, хто права не має, дає `403`, а не порожній перелік: «задач
 * немає» і «вам їх не показують» — різні відповіді.
 *
 * ⛔ Ідентифікатор власника в адресі НЕ передається і передаватися не може:
 * сервер бере його з сеансу. Параметр «чиї задачі» перетворив би звільнення
 * від права на спосіб читати чужу чергу.
 */
export function recentJobsUrl(mine: boolean): string {
  return mine ? '/api/v1/jobs?mine=true' : '/api/v1/jobs';
}

/**
 * Перелік останніх задач — своїх або всіх.
 *
 * ⚠ Опитування зупиняється, щойно в переліку не лишилося `Queued`/`Running`:
 * нескінченне опитування завершених задач — це запит на три секунди від кожної
 * відкритої вкладки.
 */
export function useRecentJobs(mine: boolean): UseQueryResult<JobSummary[]> {
  return useQuery({
    // ⚠ `mine` входить у ключ: інакше перемикання прапорця показувало б
    // кешовану відповідь на ІНШЕ питання — свої задачі під виглядом усіх.
    queryKey: ['jobs', mine],
    queryFn: () => apiFetch<JobSummary[]>(recentJobsUrl(mine)),
    refetchInterval: (query) => {
      const list = query.state.data ?? [];

      return list.some((j) => j.state === 'Queued' || j.state === 'Running') ? ListPollMs : false;
    },
  });
}

/**
 * Просить сервер зупинити фонову задачу.
 *
 * ⛔ До цієї дії довгу задачу не можна було спинити НІЯК: річний перерахунок
 * іде двадцять хвилин, а єдиним способом його обірвати було витіснення
 * зсередини планувальника (`D2-64`) — «щоб зупинити, запусти ще раз».
 *
 * ⚠ `jobId` кодується `encodeURIComponent`, і це не косметика. Ідентифікатор
 * має вигляд `IRecalculationJob#42`, а `#` в URL ПОЧИНАЄ ФРАГМЕНТ: незакодований
 * він обрізає шлях до `/api/v1/jobs/IRecalculationJob`, сервер віддає 404, і
 * виглядає це як «задачі немає», а не як зламана адреса. Саме на цьому падав
 * крок 17 `smoke.ps1`, і шістнадцять кроків перед ним проходили.
 *
 * ⚠ Відповідь — `202`, не результат: задача бачить токен і закривається станом
 * `Cancelled` на найближчій межі батчу. Стан дочитується тим самим
 * `GET /api/v1/jobs/{jobId}`, яким екран уже показує прогрес.
 */
export function cancelJob(jobId: string): Promise<AcceptedJob> {
  return apiEnqueue(`/api/v1/jobs/${encodeURIComponent(jobId)}/cancel`);
}

/**
 * Просить сервер прогнати перевірку узгодженості зараз.
 *
 * ⛔ Знахідку узгодженості НЕ МОЖНА «взяти до відома» — це пряме рішення
 * людини (`Q15-03`): вона зникає сама, коли наступна перевірка проходить. Тому
 * прогін на вимогу — єдиний спосіб зняти з переліку знахідку, причину якої вже
 * усунули; доти перевірка ходила лише за нічним розкладом, і полагоджене
 * вранці лишалося червоним до наступної ночі.
 *
 * ⚠ Причина обов'язкова: прогін іде під правом `System.RunJob` і пишеться в
 * журнал безпеки. Порожня — `422`; перевірка вже йде — `409` (`ECR-JOB-0409`)
 * з `jobId` тієї задачі в розширеннях відмови.
 *
 * ⚠ Відповідь — `202`: повний обхід партицій у відповідь не вкладається. Стан
 * дочитується тим самим `GET /api/v1/jobs/{jobId}`.
 */
export function runConsistencyCheck(reason: string): Promise<AcceptedJob> {
  return apiEnqueue('/api/v1/consistency/run', { reason });
}

/**
 * Скасування задачі як мутація React Query.
 *
 * ⚠ `onSuccess` НЕ інвалідує стан задачі, а лишає це викликачеві: екран уже
 * опитує `GET /jobs/{jobId}` з інтервалом, доки стан `Queued`/`Running`, і
 * друге джерело оновлення дало б два запити на одну подію.
 */
// ⚠ Тип помилки — `unknown`, а не `Error`: `showApiError` приймає саме його,
// і `EcrApiError` доїжджає сюди через межу, де ніхто не обіцяв класу винятку.
export function useCancelJob(
  onCancelled?: () => void,
): UseMutationResult<AcceptedJob, unknown, string> {
  return useMutation({
    mutationFn: cancelJob,
    onSuccess: () => onCancelled?.(),

    // ⛔ Причина показується кодом, а не «щось пішло не так»: `409`
    // (`ECR-JOB-0409`) означає «задача вже завершилась» — тобто кнопку треба
    // сховати, а не повторити спробу.
    onError: showApiError,
  });
}
