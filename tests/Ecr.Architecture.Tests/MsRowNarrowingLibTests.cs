using System.Diagnostics;
using System.Text;
using Ecr.TestKit;
using Xunit;

namespace Ecr.Architecture.Tests;

/// <summary>
/// c11-10 (P-1124-2, ф.2): <c>tools/Ecr.MethodologyScriptMigration/window/MsRowNarrowing.Lib.ps1</c> — які умови відбору рядків
/// скрипта недосяжні (NAE поза виразом <c>var Category</c> і поза переліком <c>reject when … Category in (…)</c>), і що текст після
/// їх зняття лишається відбором тих самих досяжних рядків. СИНТЕТИЧНИЙ скрипт форми ECW_C11_10 V4.
/// </summary>
/// <remarks>
/// Мутаційні докази (лише цей клас): не звіряти перелік дозволених категорій (<c>$facts.Allowed</c>) — червоніє
/// <c>Знімаються_лише_умови_з_NAE_поза_групами_і_поза_переліком_категорій</c> (знімається й «0646»); не переносити <c>where</c> на
/// наступну умову — червоніє <c>Знята_перша_умова_передає_where_наступній</c>; прибрати відмову для блоку без умов — червоніє
/// <c>Блок_з_усіма_недосяжними_умовами_не_стає_всією_таблицею</c>.
/// </remarks>
public sealed class MsRowNarrowingLibTests
{
    private static string Lib => Path.Combine(SourceTree.Root, "tools", "Ecr.MethodologyScriptMigration", "window", "MsRowNarrowing.Lib.ps1");

    private const string Script = """
        // Methodology ECW_X, version V4
        // Effective from 2024-01-04
        // Generated by Ecr.MethodologyScriptMigration.

        rows from T9_04
            where (row.IDCodeNAEProject == "0647 (001-002)")
               || (row.IDCodeNAEProject == "0646")
               || (row.InventoryNumberOfEquipment == "INV-1" && row.IDCodeNAEProject == "6657")
               || (row.InventoryNumberOfEquipment == "INV-2" && row.IDCodeNAEProject == "0640")
            active when row.Status == entry("LAND_GENERIC_EQUIPSTATUS", "RUNNING");

        rows from T9_07
            where (row.IDCodeNAEProject == "0880")
               || (row.IDCodeNAEProject == "0889")
            active when row.Status == entry("LAND_GENERIC_EQUIPSTATUS", "RUNNING");

        rows from T9_11
            where row.IDCodeNAEProject == "0589"
            active when row.Status == entry("LAND_GENERIC_EQUIPSTATUS", "RUNNING");

        var Category = StripSpaces(SUBSTANCE_APPLICABLE("REG", "ECW_X", "Stream", key(row.Land_TypeFuelOrStream)) ? (key(row.Land_NAE) in ("0647", "0647 (001-002)") ? "0647" : key(row.Land_NAE) in ("0885", "0889") ? "0885" : key(row.Land_NAE)) : "");
        reject when Category == null || Category == ""
            || !(Category in (
                "0589", "0646", "0647", "0885"
            ));
        """;

    private static (int Exit, string Output) RunPowerShell(string body)
    {
        var start = new ProcessStartInfo(DeployScriptHarness.FindPowerShell())
        {
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            UseShellExecute = false,
            StandardOutputEncoding = Encoding.UTF8,
            StandardErrorEncoding = Encoding.UTF8,
        };

        var script = "$ErrorActionPreference = 'Stop'\nSet-StrictMode -Version 2.0\n. '" + Lib.Replace("'", "''", StringComparison.Ordinal) + "'\n"
                     + "$text = @'\n" + Script + "\n'@\n" + body;
        var file = Path.Combine(Path.GetTempPath(), $"ecr-ms-narrow-{Guid.NewGuid():N}.ps1");
        File.WriteAllText(file, script, new UTF8Encoding(encoderShouldEmitUTF8Identifier: true));
        try
        {
            foreach (var argument in new[] { "-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-File", file })
            {
                start.ArgumentList.Add(argument);
            }

            using var process = Process.Start(start) ?? throw new InvalidOperationException("PowerShell не запустився");
            var stdout = process.StandardOutput.ReadToEnd();
            var stderr = process.StandardError.ReadToEnd();
            if (!process.WaitForExit(120_000))
            {
                process.Kill(entireProcessTree: true);
                throw new TimeoutException("PowerShell не завершився за 120 с.");
            }

            return (process.ExitCode, stdout + stderr);
        }
        finally
        {
            File.Delete(file);
        }
    }

    [Fact]
    [Trait(TestCategories.Category, TestCategories.Architecture)]
    public void Знімаються_лише_умови_з_NAE_поза_групами_і_поза_переліком_категорій()
    {
        var (exit, output) = RunPowerShell("""
            $r = Remove-MsUnreachableRowClauses -ScriptText $text -NewVersion V5 -EffectiveFrom 2024-01-05 -Note 'narrowed'
            'REMOVED=' + (($r.Removed | ForEach-Object { $_.Table + ':' + $_.Nae }) -join ',')
            '---'
            $r.Text
            """);

        Assert.True(exit == 0, output);
        Assert.Contains("REMOVED=T9_04:6657,T9_04:0640,T9_07:0880", output, StringComparison.Ordinal);
        Assert.Contains("row.IDCodeNAEProject == \"0646\"", output, StringComparison.Ordinal);            // у переліку категорій
        Assert.Contains("row.IDCodeNAEProject == \"0647 (001-002)\"", output, StringComparison.Ordinal);  // літерал групи
        Assert.Contains("row.IDCodeNAEProject == \"0889\"", output, StringComparison.Ordinal);            // член групи 0885
        Assert.Contains("where row.IDCodeNAEProject == \"0589\"", output, StringComparison.Ordinal);      // одна умова без дужок — як була
        Assert.DoesNotContain("\"0640\"", output.Split("---")[1], StringComparison.Ordinal);
        Assert.Contains("// Methodology ECW_X, version V5", output, StringComparison.Ordinal);
        Assert.Contains("// Effective from 2024-01-05", output, StringComparison.Ordinal);
        Assert.Contains("// narrowed", output, StringComparison.Ordinal);
    }

    [Fact]
    [Trait(TestCategories.Category, TestCategories.Architecture)]
    public void Знята_перша_умова_передає_where_наступній()
    {
        var (exit, output) = RunPowerShell("""
            $r = Remove-MsUnreachableRowClauses -ScriptText $text
            ($r.Text -split "`n" | Where-Object { $_ -match '0889' }) -join ''
            """);

        Assert.True(exit == 0, output);
        Assert.Contains("    where (row.IDCodeNAEProject == \"0889\")", output, StringComparison.Ordinal);
    }

    [Fact]
    [Trait(TestCategories.Category, TestCategories.Architecture)]
    public void Блок_з_усіма_недосяжними_умовами_не_стає_всією_таблицею()
    {
        var (exit, output) = RunPowerShell("""
            $bad = $text.Replace('(row.IDCodeNAEProject == "0889")', '(row.IDCodeNAEProject == "0881")')
            try { $null = Remove-MsUnreachableRowClauses -ScriptText $bad; 'NO-REFUSAL' } catch { 'REFUSED: ' + $_.Exception.Message }
            """);

        Assert.True(exit == 0, output);
        Assert.Contains("REFUSED: rows from T9_07", output, StringComparison.Ordinal);
        Assert.DoesNotContain("NO-REFUSAL", output, StringComparison.Ordinal);
    }

    [Fact]
    [Trait(TestCategories.Category, TestCategories.Architecture)]
    public void Невідома_форма_виразу_категорії_зупиняє_а_не_вгадує()
    {
        var (exit, output) = RunPowerShell("""
            $bad = $text.Replace(': key(row.Land_NAE)) : "");', ': "OTHER") : "");')
            try { $null = Remove-MsUnreachableRowClauses -ScriptText $bad; 'NO-REFUSAL' } catch { 'REFUSED: ' + $_.Exception.Message }
            """);

        Assert.True(exit == 0, output);
        Assert.Contains("REFUSED: Category expression does not fall back", output, StringComparison.Ordinal);
    }
}
