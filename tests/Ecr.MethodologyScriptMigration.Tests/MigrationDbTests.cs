    [Fact]
    [Trait(TestCategories.Category, TestCategories.Integration)]
    public async Task Shadow_записує_текст_і_хеш_а_рушій_лишається_Formulas()
    {
        var dir = await ConvertAllAsync();

        var run = await RunAsync("shadow", "--connection", sql.ConnectionString, "--in", dir);

        Assert.Equal(MigrationCli.Ok, run.Code);
        var (seed, db, _) = await OpenAsync();
        await using var _ = db;
        foreach (var (versionId, file) in new[] { (seed.LibraryVersionId, "MsLib/V1.ecrs"), (seed.MainV1Id, "MsMain/V1.ecrs") })
        {
            var text = await File.ReadAllTextAsync(Path.Combine(dir, file));
            var version = await db.MethodologyVersions.AsNoTracking().SingleAsync(v => v.Id == versionId);
            Assert.Equal(text, version.ScriptText);
            Assert.Equal(ScriptCompiler.Hash(text), version.ScriptHash);
            Assert.Equal(MethodologyEngine.Formulas, version.Engine);
        }

        var untouched = await db.MethodologyVersions.AsNoTracking().SingleAsync(v => v.Id == seed.MainV2Id);
        Assert.Null(untouched.ScriptText);
    }

