        Assert.Equal(
            Fingerprint.ComputeHex((await loader.LoadAsync(seed.MainV1Id, default)).Source),
            main.GetProperty("sourceFingerprint").GetString());

        var bytes = await File.ReadAllBytesAsync(packagePath);
        Assert.False(bytes is [0xEF, 0xBB, 0xBF, ..]);
        Assert.DoesNotContain((byte)'\r', bytes);
    }

