    [Fact]
    [Trait(TestCategories.Category, TestCategories.Integration)]
    public async Task Convert_пише_файли_і_звіт_і_завершується_кодом_1_через_невдалі_версії()
    {
        await MigrationSeed.EnsureAsync(sql.ConnectionString);
        var dir = TempDirectory();

        var run = await RunAsync("convert", "--connection", sql.ConnectionString, "--out", dir);

        Assert.Equal(MigrationCli.Failures, run.Code);

        // Золоті тексти; кодування — UTF-8 без BOM, переведення рядка — LF.
        var libraryBytes = await File.ReadAllBytesAsync(Path.Combine(dir, "MsLib", "V1.ecrs"));
        Assert.False(libraryBytes is [0xEF, 0xBB, 0xBF, ..]);
        Assert.DoesNotContain((byte)'\r', libraryBytes);
        Assert.Equal(LibraryGolden.ReplaceLineEndings("\n"), Encoding.UTF8.GetString(libraryBytes));
        Assert.Equal(
            MainGolden.ReplaceLineEndings("\n"),
            await File.ReadAllTextAsync(Path.Combine(dir, "MsMain", "V1.ecrs")));

        // Невдалі, пропущені — без файлів.
        Assert.False(File.Exists(Path.Combine(dir, "MsMain", "V2.ecrs")));
        Assert.False(File.Exists(Path.Combine(dir, "MsBroken", "B1.ecrs")));
        Assert.False(File.Exists(Path.Combine(dir, "MsModule", "M1.ecrs")));
        Assert.False(File.Exists(Path.Combine(dir, "MsScripted", "S1.ecrs")));

        using var report = JsonDocument.Parse(await File.ReadAllTextAsync(Path.Combine(dir, "convert-report.json")));
        var root = report.RootElement;
        Assert.Equal((2, 2, 3), (root.GetProperty("converted").GetInt32(), root.GetProperty("failed").GetInt32(), root.GetProperty("skipped").GetInt32()));

        JsonElement Entry(string methodology, string version)
            => root.GetProperty("versions").EnumerateArray().Single(
                v => v.GetProperty("methodology").GetString() == methodology && v.GetProperty("version").GetString() == version);

        Assert.Equal("Converted", Entry("MsMain", "V1").GetProperty("status").GetString());
        Assert.Equal("MsMain/V1.ecrs", Entry("MsMain", "V1").GetProperty("file").GetString());
        Assert.Equal(64, Entry("MsMain", "V1").GetProperty("sourceFingerprint").GetString()!.Length);
        Assert.Equal("Failed", Entry("MsMain", "V2").GetProperty("status").GetString());
        Assert.Contains(
            Entry("MsMain", "V2").GetProperty("issues").EnumerateArray(),
            i => i.GetProperty("code").GetString() == "rowsNoRules" && i.GetProperty("severity").GetString() == "Error");
        Assert.Contains(
            Entry("MsBroken", "B1").GetProperty("issues").EnumerateArray(),
            i => i.GetProperty("code").GetString() == "ruleColumnNotFound");
        Assert.Equal("Level Module", Entry("MsModule", "M1").GetProperty("reason").GetString());
        Assert.Equal("already Script", Entry("MsScripted", "S1").GetProperty("reason").GetString());
        Assert.Equal("Skipped", Entry("MsDraft", "D1").GetProperty("status").GetString());

        var reportBytes = await File.ReadAllBytesAsync(Path.Combine(dir, "convert-report.json"));
        Assert.False(reportBytes is [0xEF, 0xBB, 0xBF, ..]);
        Assert.DoesNotContain((byte)'\r', reportBytes);
    }

