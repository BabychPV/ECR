    [Fact]
    [Trait(TestCategories.Category, TestCategories.Integration)]
    public async Task Завантажувач_читає_основну_версію_повністю()
    {
        var (seed, db, loader) = await OpenAsync();
        await using var _ = db;

        var loaded = await loader.LoadAsync(seed.MainV1Id, default);
        Assert.False(loaded.HasErrors, string.Join("; ", loaded.Issues.Select(i => i.Code + ": " + i.Message)));
        var source = loaded.Source;

        Assert.Equal(MigrationSeed.Main, source.MethodologyCode);
        Assert.Equal("V1", source.VersionLabel);
        Assert.False(source.IsLibrary);
        Assert.Equal(new DateOnly(2024, 1, 1), source.EffectiveFrom);
        Assert.Equal(new DateOnly(2026, 1, 1), source.NextEffectiveFrom);
        Assert.Equal("MS_STATUS:RUNNING", source.RowActivityFilter);

        Assert.Equal(["Mass", "Emission"], source.Formulas.Select(f => f.Code));
        var mass = source.Formulas[0];
        Assert.Equal(("t", MethodologyFormulaScope.Row, true), (mass.UnitCode, mass.Scope, mass.IsVisible));
        Assert.Equal(MethodologyFormulaScope.Substance, source.Formulas[1].Scope);

        var output = Assert.Single(source.Outputs);
        Assert.Equal(("Emission", "t", true), (output.Code, output.UnitCode, output.IsPerSubstance));

        Assert.Equal(["A", "B"], source.Categories);
        Assert.Equal("if(@Zone = 'North', 'A', 'B')", source.CategoryRule);

        // Код речовини — з поля SUBSTANCE_CODE (код запису — E301), порядок — за Ordinal.
        Assert.Equal(["0301", "0304"], source.Substances);
        Assert.Equal(
            [("0301", null, new DateOnly(2025, 6, 1)), ("0301", new DateOnly(2025, 6, 1), null), ("0304", new DateOnly(2000, 1, 1), null)],
            source.Constants.Select(c => (c.SubstanceCode!, c.ValidFrom, c.ValidTo)).OrderBy(c => c.Item1).ThenBy(c => c.Item2));
        Assert.All(source.Constants, c => Assert.Equal("kg", c.UnitCode));

        var import = Assert.Single(source.Imports);
        Assert.Equal("MsLib", import.LibraryCode);
        Assert.Equal(["Dens"], import.Members);
        // Склад імпорту — з замикання (Emission читає !Dens): категорії констант бібліотеки досяжні, маркерів немає.
        Assert.Equal(["A", "B"], import.ConstantCategories);
        Assert.Empty(import.OptionalArguments!);
    }

    [Fact]
    [Trait(TestCategories.Category, TestCategories.Integration)]
    public async Task Завантажувач_будує_речення_rows_із_правилами_і_активністю()
    {
        var (seed, db, loader) = await OpenAsync();
        await using var _ = db;

        var source = (await loader.LoadAsync(seed.MainV1Id, default)).Source;

        // Правила: активні за пріоритетом (неактивне R_OFF — ні); ключі — коди колонок;
        // значення колонки-Lookup — запис довідника за кодом, текст — текстом.
        Assert.Equal(2, source.Rules.Count);
        var first = source.Rules[0].Pairs.ToDictionary(p => p.ColumnCode);
        Assert.Equal(("MS_FUEL", "GAS"), (first["Fuel"].Value.RegistryCode, first["Fuel"].Value.EntryCode));
        Assert.Equal("North", first["Zone"].Value.Text);
        var second = Assert.Single(source.Rules[1].Pairs);
        Assert.Equal(("Zone", "South"), (second.ColumnCode, second.Value.Text));

        // Таблиці — усі прив'язки (і неактивна на T2); різні набори статус-колонок — різні речення.
        Assert.Equal(2, source.RowsClauses.Count);
        var t1 = Assert.Single(source.RowsClauses, c => c.TableCodes.SequenceEqual(["MS_T1"]));
        var active = Assert.Single(t1.ActiveColumns);
        Assert.Equal(("State", "MS_STATUS", "RUNNING"), (active.ColumnCode, active.RegistryCode, active.EntryCode));
        var t2 = Assert.Single(source.RowsClauses, c => c.TableCodes.SequenceEqual(["MS_T2"]));
        Assert.Empty(t2.ActiveColumns);
    }

