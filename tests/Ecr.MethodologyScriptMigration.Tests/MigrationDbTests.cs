    private const string LibraryGolden = """
        // Methodology MsLib, version V1 (library)
        // Effective from 2024-01-01
        // Generated by Ecr.MethodologyScriptMigration.

        param Category;
        const K : kg = {
            A: 1.5,
            B: 2.5,
        };

        var Dens = K[Category] * 2;

        """;

    private const string MainGolden = """
        // Methodology MsMain, version V1
        // Effective from 2024-01-01 until 2026-01-01 (exclusive)
        // Generated by Ecr.MethodologyScriptMigration.

        import MsLib;

        rows from MS_T1
            where (row.Fuel == entry("MS_FUEL", "GAS") && row.Zone == "North")
               || (row.Zone == "South")
            active when row.State == entry("MS_STATUS", "RUNNING");

        rows from MS_T2
            where (row.Fuel == entry("MS_FUEL", "GAS") && row.Zone == "North")
               || (row.Zone == "South");

        const EF_from_20240101 : kg = {
            "0301": 0.5,
            "0304": 0.7,
        };
        const EF_from_20250601 : kg = {
            "0301": 0.6,
            "0304": 0.7,
        };
        function EF(k_substance) = period.EndKey >= 20250601 ? EF_from_20250601[k_substance] : EF_from_20240101[k_substance];

        visible var Mass : t = row.Qty * 2;

        var Category = StripSpaces(key(row.Zone) == "North" ? "A" : "B");
        reject when Category == null || Category == "" || !(Category in ("A", "B"));

        foreach substance S in ("0301", "0304") {
            output Emission per S : t = Mass * EF(S.code) * MsLib.Dens;
        }

        """;

    private async Task<(SeedResult Seed, EcrDbContext Db, VersionSourceLoader Loader)> OpenAsync()
    {
        var seed = await MigrationSeed.EnsureAsync(sql.ConnectionString);
        var db = MigrationCli.CreateContext(sql.ConnectionString, readOnly: true);
        return (seed, db, new VersionSourceLoader(db, MigrationCli.CreateFormulaEngine()));
    }

    private static string TempDirectory()
    {
        var path = Path.Combine(Path.GetTempPath(), "ecr-ms-migration-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(path);
        return path;
    }

    private static async Task<(int Code, string Output, string Error)> RunAsync(params string[] args)
    {
        var output = new StringWriter();
        var error = new StringWriter();
        var code = await MigrationCli.RunAsync(args, output, error, CancellationToken.None);
        return (code, output.ToString(), error.ToString());
    }

    private async Task<string> ConvertAllAsync()
    {
        await MigrationSeed.EnsureAsync(sql.ConnectionString);
        var dir = TempDirectory();
        await RunAsync("convert", "--connection", sql.ConnectionString, "--out", dir);
        return dir;
    }

