using Ecr.Domain.Enums;
using Ecr.MethodologyScriptMigration.Conversion;
using Ecr.Scripting;
using Xunit;

namespace Ecr.MethodologyScriptMigration.Tests;

public sealed class ConverterTests
{
    private const MethodologyFormulaScope Row = MethodologyFormulaScope.Row;

    [Fact]
    public void Макет_заголовок_імпорти_rows_константи_оператори()
    {
        var source = Sup.Version(
            [
                Sup.F("Hours", "@Hours * CST.k", 1, Row),
                Sup.F("Idle", "if(!Hours = 0, 1, 0)", 2, Row, visible: true, unit: "one"),
                Sup.F("EC_t", "!Hours * 2", 3),
            ],
            [SourceConstant.OfNumber("k", 5)],
            [new SourceOutput("EC_t", "t")]);

        var result = Sup.ConvertOk(source);
        Assert.Equal(
            string.Join(
                "\n",
                "// Methodology M1, version V1",
                "// Effective from 2024-01-01",
                "// Generated by Ecr.MethodologyScriptMigration.",
                "",
                "rows from T1;",
                "",
                "const k = 5;",
                "",
                "var Hours = row.Hours * k;",
                "visible var Idle : one = Hours == 0 ? 1 : 0;",
                "",
                "output EC_t : t = Hours * 2;",
                string.Empty),
            result.Text);
        var script = Sup.Compile(result.Text!);
        Assert.Equal("EC_t", Assert.Single(script.Outputs).Code);
        Assert.Equal("Idle", Assert.Single(script.Visibles).Code);
    }

    [Fact]
    public void Конвертація_детермінована()
    {
        var source = Sup.Version([Sup.F("A", "@X * CST.k", 1)], [SourceConstant.OfNumber("k", 1)], [new SourceOutput("A", "t")]);
        Assert.Equal(ScriptConverter.Convert(source).Text, ScriptConverter.Convert(source).Text);
    }

    [Fact]
    public void Порядок_операторів_за_EvaluationOrder_а_не_за_порядком_списку()
    {
        var source = Sup.Version(
            [Sup.F("B", "!A + 1", 20), Sup.F("A", "@X", 10)]);

        var text = Sup.ConvertOk(source).Text!;
        Assert.True(text.IndexOf("var A =", StringComparison.Ordinal) < text.IndexOf("var B =", StringComparison.Ordinal));
    }

    [Fact]
    public void Row_формули_до_правила_категорії_і_циклу_речовин()
    {
        var source = Sup.Version(
            [
                Sup.F("RowVar", "@X", 1, Row),
                Sup.F("Sub", "CST.K * !RowVar", 2),
            ],
            [SourceConstant.OfNumber("K", 1, null, "0301"), SourceConstant.OfNumber("K", 2, null, "0304")],
            [new SourceOutput("Sub", "t")],
            categoryRule: "@Fuel",
            categories: ["A"],
            substances: ["0301", "0304"]);

        var text = Sup.ConvertOk(source).Text!;
        var rowVar = text.IndexOf("var RowVar", StringComparison.Ordinal);
        var category = text.IndexOf("var Category", StringComparison.Ordinal);
        var loop = text.IndexOf("foreach substance S", StringComparison.Ordinal);
        Assert.True(rowVar < category && category < loop);
        Assert.Contains("    output Sub per S : t = K[S.code] * RowVar;", text);
        Sup.Compile(text);
    }

    [Fact]
    public void Правило_категорії_читає_аргументи_ключем_і_перевіряє_відомі_категорії()
    {
        var source = Sup.Version(
            [Sup.F("A", "CST.K", 1)],
            [SourceConstant.OfNumber("K", 1, "X"), SourceConstant.OfNumber("K", 2, "Y")],
            categoryRule: "if(@Fuel = 'a', 'X', 'Y')",
            categories: ["X", "Y"]);

        var text = Sup.ConvertOk(source).Text!;
        Assert.Contains("var Category = StripSpaces(key(row.Fuel) == \"a\" ? \"X\" : \"Y\");", text);
        Assert.Contains("reject when Category == null || Category == \"\" || !(Category in (\"X\", \"Y\"));", text);
    }

    [Fact]
    public void Правило_із_SUBSTANCE_APPLICABLE_дає_SubstanceCategory_і_skip_у_циклі()
    {
        var source = Sup.Version(
            [Sup.F("A", "CST.K", 1)],
            [SourceConstant.OfNumber("K", 1, "X", "0301"), SourceConstant.OfNumber("K", 2, "X", "0304")],
            categoryRule: "if(SUBSTANCE_APPLICABLE(@Fuel, 'a', 'b', 'c'), 'X', '')",
            categories: ["X"],
            substances: ["0301", "0304"]);

        var text = Sup.ConvertOk(source).Text!;
        Assert.Contains("    var SubstanceCategory = StripSpaces(SUBSTANCE_APPLICABLE(key(row.Fuel), \"a\", \"b\", \"c\") ? \"X\" : \"\");", text);
        Assert.Contains("    skip when SubstanceCategory == null || SubstanceCategory == \"\";", text);
        Assert.Contains("var A = K[S.code];", text);
    }

    [Fact]
    public void Імпорт_і_формула_бібліотеки_стає_Lib_Name()
    {
        var source = Sup.Version(
            [Sup.F("A", "!Common_X * 2 + !Own", 2), Sup.F("Own", "@Y", 1)],
            imports: [new SourceImport("Common", ["Common_X"])]);

        var result = Sup.ConvertOk(source);
        Assert.Contains("import Common;", result.Text);
        Assert.Contains("var A = Common.Common_X * 2 + Own;", result.Text);
    }

    [Fact]
    public void Посилання_що_не_розвязується_або_неоднозначне_дає_Error()
    {
        var unknown = ScriptConverter.Convert(Sup.Version([Sup.F("A", "!Nowhere", 1)]));
        Assert.Null(unknown.Text);
        Assert.True(Sup.HasIssue(unknown, "unknownReference", IssueSeverity.Error));

        var ambiguous = ScriptConverter.Convert(Sup.Version(
            [Sup.F("A", "!X", 1)],
            imports: [new SourceImport("L1", ["X"]), new SourceImport("L2", ["x"])]));
        Assert.Null(ambiguous.Text);
        Assert.True(Sup.HasIssue(ambiguous, "ambiguousReference", IssueSeverity.Error));
    }

    [Fact]
    public void Бібліотека_без_rows_і_output_з_var_замість_формул()
    {
        var source = new VersionSource
        {
            MethodologyCode = "Common",
            IsLibrary = true,
            Formulas = [Sup.F("Density", "CST.rho * 2", 1), Sup.F("Mass", "!Density * 3", 2)],
            Constants = [SourceConstant.OfNumber("rho", 0.85m, "Common")],
        };

        var result = Sup.ConvertOk(source);
        Assert.DoesNotContain("rows", result.Text);
        Assert.DoesNotContain("output", result.Text);
        Assert.Contains("// Methodology Common, version V1 (library)", result.Text);
        Assert.Contains("var Density = rho * 2;", result.Text);
        var lib = Sup.Compile(result.Text!, library: true);
        Assert.Contains(lib.Members, m => m.Name == "Mass");
    }

    [Fact]
    public void Бібліотека_з_виходами_і_версія_без_rows_не_перетворюються()
    {
        var withOutput = new VersionSource
        {
            MethodologyCode = "L",
            IsLibrary = true,
            Formulas = [Sup.F("A", "1", 1)],
            Outputs = [new SourceOutput("A", "t")],
        };
        Assert.Null(ScriptConverter.Convert(withOutput).Text);

        var noRows = Sup.Version([Sup.F("A", "1", 1)]) with { RowsClauses = [] };
        var result = ScriptConverter.Convert(noRows);
        Assert.Null(result.Text);
        Assert.True(Sup.HasIssue(result, "missingRows", IssueSeverity.Error));
    }

    [Fact]
    public void Назва_формули_що_збігається_з_ключовим_словом_отримує_суфікс_f()
    {
        var result = Sup.ConvertOk(Sup.Version([Sup.F("key", "@X", 1), Sup.F("B", "!key + 1", 2)]));
        Assert.Contains("var key_f = row.X;", result.Text);
        Assert.Contains("var B = key_f + 1;", result.Text);
        Assert.True(Sup.HasIssue(result, "nameCollision", IssueSeverity.Info));
    }

    [Fact]
    public void Вихід_з_назвою_ключового_слова_не_перетворюється()
    {
        var result = ScriptConverter.Convert(Sup.Version([Sup.F("row", "1", 1)], outputs: [new SourceOutput("row", "t")]));
        Assert.Null(result.Text);
        Assert.True(result.HasErrors);
    }

    [Fact]
    public void Вихід_не_по_речовині_з_формулою_речовини_відхиляється()
    {
        var result = ScriptConverter.Convert(Sup.Version(
            [Sup.F("A", "1", 1)],
            outputs: [new SourceOutput("A", "t", IsPerSubstance: false)],
            substances: ["0301"]));
        Assert.Null(result.Text);
        Assert.True(Sup.HasIssue(result, "outputScopeMismatch", IssueSeverity.Error));
    }

    [Fact]
    public void Посилання_вперед_і_на_себе_відхиляються_з_поясненням()
    {
        var result = ScriptConverter.Convert(Sup.Version([Sup.F("A", "!B", 1), Sup.F("B", "1", 2), Sup.F("C", "!C", 3)]));
        Assert.Null(result.Text);
        Assert.Equal(2, result.Issues.Count(i => i.Code == "forwardReference"));
    }

    [Fact]
    public void Вираз_що_не_переноситься_дає_Error_без_тексту()
    {
        var result = ScriptConverter.Convert(Sup.Version([Sup.F("A", "2 ^ 3", 1)]));
        Assert.Null(result.Text);
        Assert.True(Sup.HasIssue(result, "expressionParse", IssueSeverity.Error));
    }

    [Fact]
    public void Самоперевірка_компілятором_ловить_функцію_не_дозволену_в_режимі()
    {
        // Ln — лише Strict; старий розбір її приймає, а компілятор скрипта в режимі Legacy — ні.
        var result = ScriptConverter.Convert(Sup.Version([Sup.F("A", "Ln(@X)", 1)]));
        Assert.Null(result.Text);
        Assert.Contains(result.Issues, i => i.Code == "scriptCompile" && i.Message.Contains("functionNotAllowedInMode", StringComparison.Ordinal));
    }

    [Fact]
    public void Видима_формула_без_виходу_стає_visible_var_з_одиницею()
    {
        var result = Sup.ConvertOk(Sup.Version([Sup.F("V", "@X", 1, visible: true, unit: "m3")]));
        Assert.Contains("visible var V : m3 = row.X;", result.Text);
    }

    [Fact]
    public void Формула_без_речовин_і_вихід_по_речовині_пишуться_без_per()
    {
        var result = Sup.ConvertOk(Sup.Version(
            [Sup.F("A", "@X", 1)], outputs: [new SourceOutput("A", "t", IsPerSubstance: true)]));
        Assert.Contains("output A : t = row.X;", result.Text);
        Assert.DoesNotContain(" per ", result.Text);
    }

    [Fact]
    public void Голий_параметр_лишає_Info_про_режим_імпорту()
    {
        var result = Sup.ConvertOk(Sup.Version([Sup.F("A", "Duration * 2", 1)]));
        Assert.Contains("row.Duration * 2", result.Text);
        Assert.True(Sup.HasIssue(result, "parsedInImportMode", IssueSeverity.Info));
    }
}
