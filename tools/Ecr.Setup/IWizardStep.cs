namespace Ecr.Setup;

/// <summary>
/// Один екран майстра. <see cref="MainForm"/> викликає <see cref="BuildView"/>
/// рівно один раз на крок (кешує результат), <see cref="Validate"/> — при
/// кожному натисканні "Далі", <see cref="Apply"/> — одразу після успішної
/// валідації, перед переходом на наступний крок.
/// </summary>
internal interface IWizardStep
{
    public string Title { get; }

    public Control BuildView();

    public bool Validate(out string error);

    public void Apply(WizardState state);

    /// <summary>
    /// Викликається щоразу, коли крок стає поточним (і вперше, і при
    /// поверненні "Назад"/повторному "Далі") — ПІСЛЯ <see cref="BuildView"/>,
    /// яка натомість викликається лише один раз. Порожня реалізація за
    /// замовчуванням: більшості кроків нічого освіжати не треба, оскільки
    /// вони самі володіють своїми полями. Явно перевизначають лише кроки,
    /// чий вигляд залежить від відповідей ІНШИХ кроків: "Огляд" (перечитує
    /// весь <see cref="WizardState"/> заново після можливих правок після
    /// повернення назад) і "База даних" (показує прапорець "Схема вже
    /// накочена" лише в режимі оновлення).
    /// </summary>
    public void OnShow(WizardState state)
    {
    }
}
