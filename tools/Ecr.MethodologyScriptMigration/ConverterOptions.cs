namespace Ecr.MethodologyScriptMigration;

/// <summary>Перемикачі перетворювача, що залежать від можливостей компілятора «ECR Script».</summary>
public static class ConverterOptions
{
    /// <summary>
    /// ПЕРЕМИКАЧ: чи знає компілятор мови конструкцію бібліотеки <c>param Ім'я;</c> (значення — змінна імпортера
    /// з тим самим ім'ям під час обчислення, <c>null</c>, якщо в імпортера її немає).
    /// </summary>
    /// <remarks>
    /// Поки <c>false</c> (компілятор ще без <c>param</c>), самоперевірка перетворювача пропускає скрипти, що містять
    /// <c>param</c>: інакше кожна бібліотека з константою «за категорією» мала б помилку компіляції. Коли компілятор
    /// навчиться — змінити на <c>true</c>: самоперевірка знову компілюватиме все. Єдине місце, що це вмикає.
    /// </remarks>
    public static bool LanguageHasParam { get; set; }
}
